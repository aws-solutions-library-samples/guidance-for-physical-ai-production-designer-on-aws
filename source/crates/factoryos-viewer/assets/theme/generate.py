#!/usr/bin/env python3
"""Makes the Kiro themes of the viewer (see src/theme.rs) from re_ui's stock design tokens.

    python3 crates/factoryos-viewer/assets/theme/generate.py

re_ui's tokens name colours of a table (`{Gray.100}`, `{Blue.500}`, ...). Each Kiro theme gets its
own table: the Gray scale is re-anchored on Kiro Crew's surfaces and text colours (its
`kiro-dark` / `kiro-light` palettes, website/src/styles/theme-palettes.css), and the Blue scale,
which re_ui uses for selection, focus and primary buttons, becomes a purple scale around Kiro's
accent `#8e48ff`. The theme files are re_ui's own with a few tokens changed (TOKEN_EDITS). Rerun's
checkout must be at third_party/rerun/src (scripts/fetch-rerun.sh).
"""

import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
RE_UI = HERE.parents[3] / "third_party/rerun/src/crates/viewer_support/re_ui/data"

# Kiro colours at some steps of the 0 (black) .. 1000 (white) scale; the steps between are
# interpolated. Dark: the page (Gray.0) is Kiro's bg, panels (100) its panel, fields (200) its
# hover, strokes (250/300) its borders, subdued text (550) muted, default text (750) text.
GRAY_DARK = {
    0: "#19161d", 50: "#1c1922", 100: "#211d25", 150: "#241f29", 200: "#28242e",
    250: "#2f2a36", 300: "#352f3d", 350: "#4a464f", 450: "#5e5966", 550: "#938f9b",
    650: "#b3b0b8", 750: "#dcdadf", 900: "#f2f1f4", 1000: "#ffffff",
}
# Light: strong text (Gray.0) is Kiro's text-strong, default text (250) its text, subdued (500)
# muted, strokes (800) its border, fields (900) its hover, the page (975) its panel and panels
# (1000) white.
GRAY_LIGHT = {
    0: "#19161d", 150: "#2e2a33", 250: "#4a464f", 400: "#5e5966", 500: "#6e6976",
    650: "#a1a1aa", 750: "#d4d4d8", 800: "#e4e4e7", 900: "#f0f0f0", 950: "#f5f5f5",
    975: "#fafafa", 1000: "#ffffff",
}
# The accent scale: 500 is the accent (selection, primary buttons), 400/350 focus, 750 / 900 icons
# and text on the accent.
PURPLE = {
    0: "#000000", 200: "#1f0b45", 350: "#5a22c4", 400: "#6f33e6", 500: "#8e48ff",
    600: "#9f63ff", 700: "#b07fff", 750: "#c19aff", 900: "#efe6ff", 1000: "#ffffff",
}

# Token changes on top of re_ui's theme files: (token, old colour, new colour).
TOKEN_EDITS = {
    "dark": [],
    # re_ui's light top bar is grey (Gray.800); Kiro's chrome is white.
    "light": [("top_bar_color", "{Gray.800}", "{Gray.1000}")],
}


def rgb(hex_color):
    return tuple(int(hex_color[i : i + 2], 16) for i in (1, 3, 5))


def ramp(anchors, step):
    """The colour at `step`, linearly between the nearest anchors."""
    steps = sorted(anchors)
    if step in anchors:
        return anchors[step]
    lo = max(s for s in steps if s < step)
    hi = min(s for s in steps if s > step)
    t = (step - lo) / (hi - lo)
    a, b = rgb(anchors[lo]), rgb(anchors[hi])
    return "#" + "".join(f"{round(x + (y - x) * t):02x}" for x, y in zip(a, b))


def color_table(gray):
    table = json.loads((RE_UI / "color_table.ron").read_text())
    colors = table["Global"]["Color"]
    for name, anchors in (("Gray", gray), ("Blue", PURPLE)):
        for step, entry in colors[name].items():
            entry["value"] = ramp(anchors, int(step))
    return json.dumps(table, indent=2) + "\n"


def theme(mode):
    text = (RE_UI / f"{mode}_theme.ron").read_text()
    for token, old, new in TOKEN_EDITS[mode]:
        pattern = re.compile(rf'("{token}"\s*:\s*\{{\s*"color"\s*:\s*"){re.escape(old)}"')
        text, n = pattern.subn(rf'\g<1>{new}"', text)
        assert n == 1, f"{mode}: {token} is not {old} in re_ui's theme"
    return text


def main():
    header = "// Generated by generate.py from re_ui's data/{}; do not edit.\n"
    for mode, gray in (("dark", GRAY_DARK), ("light", GRAY_LIGHT)):
        (HERE / f"kiro_{mode}_colors.ron").write_text(color_table(gray))
        (HERE / f"kiro_{mode}_theme.ron").write_text(header.format(f"{mode}_theme.ron") + theme(mode))
    print(f"wrote the Kiro themes to {HERE}")


if __name__ == "__main__":
    main()
