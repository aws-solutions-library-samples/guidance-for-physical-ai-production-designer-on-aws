fn s(ms: u64) -> String {
    format!("{:.3}", ms as f64 / 1000.0)
}

/// `NAME := value` pairs of an enum DUT (for the error-code table).
fn enum_values(p: &PlcProject, name: &str) -> Vec<(String, String)> {
    let Some(o) = p.object(name) else {
        return Vec::new();
    };
    let t = strip_comments(&o.decl);
    let Some(open) = t.find('(') else {
        return Vec::new();
    };
    let Some(close) = t[open..].find(')') else {
        return Vec::new();
    };
    t[open + 1..open + close]
        .split(',')
        .filter_map(|item| {
            let mut it = item.split(":=");
            let n = it.next()?.trim().to_string();
            let v = it.next()?.trim().to_string();
            (!n.is_empty()).then_some((n, v))
        })
        .collect()
}

fn tree(out: &mut String, n: &DeviceNode, depth: usize) {
    let pad = "  ".repeat(depth);
    let _ = writeln!(
        out,
        "{pad}- **{}**  `({}, '{}', '{}')`",
        n.name, n.device_id.ty, n.device_id.id, n.device_id.version
    );
    for p in &n.parameters {
        let what = p
            .member
            .map(|m| format!("{} . {m}", p.id))
            .unwrap_or_else(|| format!("{} {}", p.id, p.name.unwrap_or("")));
        let _ = writeln!(out, "{pad}  - param {what} = `{}`", p.value);
    }
    for sl in &n.slots {
        let Some(module_id) = sl.module_id.filter(|_| !sl.empty) else {
            let _ = writeln!(
                out,
                "{pad}  - slot {}: **empty** (SIMULATION ONLY, safety_module = false: unplug the \
                 default module the device comes with, FDIO64 on DAP DIM 3)",
                sl.slot
            );
            continue;
        };
        let _ = writeln!(
            out,
            "{pad}  - slot {}: **{}** module id `{}` (ident {}){}",
            sl.slot,
            sl.name,
            module_id,
            sl.ident,
            if sl.profisafe { ", PROFIsafe" } else { "" }
        );
    }
    for c in &n.children {
        tree(out, c, depth + 1);
    }
}

fn zones_summary(out: &mut String, plan: &CellPlan) {
    if plan.zones.is_empty() {
        out.push_str("No cross-robot dependencies: no interlock zones.\n");
    }
    for z in &plan.zones {
        let t: Vec<String> = z
            .tickets
            .iter()
            .map(|t| {
                format!(
                    "{}#{} {}",
                    plan.robots[t.robot].addr.tag, t.op_index, plan.ops[t.op].operation_id
                )
            })
            .collect();
        let _ = writeln!(out, "- **{}** (bit {}): {}", z.name, z.index, t.join(" > "));
    }
    if !plan.permit_edges.is_empty() {
        let _ = writeln!(
            out,
            "- **PERMIT** (bit 31): {} dependencies beyond the zone capacity",
            plan.permit_edges.len()
        );
    }
}

pub fn project_md(plan: &CellPlan, cfg: &Config, projects: &[PlcProject], m: &Manifest) -> String {
    let mut o = String::new();
    let _ = writeln!(o, "# CODESYS build guide - {}\n", plan.cell_id);
    let _ = writeln!(
        o,
        "Generated by {GENERATOR} from `{}` (tree `{}`, plan id {}). Machine-readable twin: `project.json`; agent procedure: `MCP_PROMPT.md`.\n",
        plan.source_file, plan.tree_id, m.plan.plan_id
    );
    o.push_str("## 1. Overview\n\n| Tag | Robot | Station | Device | IP | Ops | Zones used | Prod. Folge |\n|---|---|---|---|---|---|---|---|\n");
    for r in &plan.robots {
        let zones: std::collections::BTreeSet<String> = r
            .ops
            .iter()
            .flat_map(|&o| {
                plan.ops[o]
                    .zones
                    .iter()
                    .map(|&z| plan.zones[z].name.clone())
            })
            .collect();
        let _ = writeln!(
            o,
            "| {} | {} | {} | {} | {} | {} | {} | {} |",
            r.addr.tag,
            r.ns,
            r.addr.station,
            r.addr.device_name,
            r.addr.ip,
            if r.idle {
                "idle".to_string()
            } else {
                r.ops.len().to_string()
            },
            if zones.is_empty() {
                "-".to_string()
            } else {
                zones.into_iter().collect::<Vec<_>>().join(", ")
            },
            r.addr.prod_folge
        );
    }
    let _ = writeln!(
        o,
        "\nPlanned cycle time (ASAP, nominal durations): **{} s**. Grant policy: **{}**. Home Folge: {}. Job number: {}.\n",
        s(plan.makespan_ms),
        if plan.grant_policy == GrantPolicy::Planned {
            "planned ticket order"
        } else {
            "FCFS - BT order not enforced"
        },
        cfg.cell.home_folge,
        match cfg.cell.job_number {
            crate::config::JobNumber::WordLe => "WORD little-endian in bytes 2-3",
            crate::config::JobNumber::Byte => "byte 2",
        }
    );
    o.push_str(
        "Interlock zones (robot-held mutex bits, granted by the head PLC in ticket order):\n\n",
    );
    zones_summary(&mut o, plan);
    let n = &cfg.network;
    let _ = writeln!(
        o,
        "\n## 2. Network\n\nPROFINET subnet {} / {} on interface `{}`. Head PLC (PN-Controller `{}`) at {} (gateway port {}, OPC UA {}); device IP pool {} .. {}.\nEach robot simulator is its own CODESYS runtime (one PN device per runtime, unique station name); see `docker/README.md`.\n",
        std::net::Ipv4Addr::from(u32::from(n.head_ip) & u32::from(n.netmask)),
        n.netmask,
        n.nic,
        n.controller_station,
        n.head_ip,
        n.head_gateway_port,
        n.head_opcua_port,
        n.ip_pool_first,
        n.ip_pool_last
    );
    o.push_str("## 3. Prerequisites (once per CODESYS installation)\n\n");
    for p in &m.prerequisites {
        let _ = writeln!(
            o,
            "- `{}` ({}): {} -> provides `({}, '{}', '{}')`",
            p.id,
            p.kind,
            p.file
                .clone()
                .or(p.how.map(str::to_string))
                .unwrap_or_default(),
            p.provides.ty,
            p.provides.id,
            p.provides.version
        );
    }
    for (pi, p) in m.projects.iter().enumerate() {
        let proj = &projects[pi];
        let _ = writeln!(
            o,
            "\n## {}. Project `{}` ({})\n",
            4 + pi,
            p.name,
            if p.role == ProjectRole::HeadPlc {
                "head PLC"
            } else {
                "robot simulator"
            }
        );
        let _ = writeln!(
            o,
            "Sources: `{}/` - runtime `{}` at {} (gateway port {}).\n\n### Device tree\n",
            p.source_dir, p.runtime.container, p.runtime.ip, p.runtime.gateway_port
        );
        tree(&mut o, &p.device_tree, 0);
        o.push_str("\n### IO mapping\n\n| Module | Param | Channel | Sub | Dir | Variable |\n|---|---|---|---|---|---|\n");
        fn walk(o: &mut String, n: &DeviceNode) {
            for sl in &n.slots {
                for io in &sl.io {
                    let _ = writeln!(
                        o,
                        "| {} | {} | {} | {} | {} | `{}` |",
                        sl.name,
                        io.param_id,
                        io.channel,
                        io.sub.map(|v| v.to_string()).unwrap_or_else(|| "-".into()),
                        io.dir,
                        io.variable
                    );
                }
            }
            for c in &n.children {
                walk(o, c);
            }
        }
        walk(&mut o, &p.device_tree);
        o.push_str("\n### Tasks\n\n| Task | Interval | Priority | POUs |\n|---|---|---|---|\n");
        for t in &p.tasks {
            let _ = writeln!(
                o,
                "| {} | {} | {} | {}{} |",
                t.name,
                t.interval,
                t.priority,
                t.pous.join(", "),
                t.bus_cycle_task_of
                    .as_ref()
                    .map(|b| format!(" (bus cycle task of {b})"))
                    .unwrap_or_default()
            );
        }
        o.push_str("\n### Libraries\n\n");
        for l in &p.libraries {
            let _ = writeln!(o, "- {} {} ({})", l.name, l.version.unwrap_or("*"), l.mode);
        }
        o.push_str("\n### Objects (creation order, all under `Application`)\n\n| # | Object | Kind | Declaration | Implementation | Origin |\n|---|---|---|---|---|---|\n");
        for ob in &p.objects {
            let _ = writeln!(
                o,
                "| {} | {} | {}{} | `{}` | {} | {:?} |",
                ob.order,
                ob.name,
                ob.kind,
                ob.pou_type.map(|t| format!(" ({t})")).unwrap_or_default(),
                ob.declaration,
                ob.implementation
                    .as_ref()
                    .map(|i| format!("`{i}`"))
                    .unwrap_or_else(|| "-".into()),
                ob.origin
            );
        }
        if proj.role == ProjectRole::HeadPlc {
            o.push_str("\n### Operation\n\n`PLC_PRG` operator inputs: `bAutoRun`, `bStart` (rising edge), `bStop`, `bReset` (rising edge), `bRecoveryConfirm` (rising edge; needed after a mid-cycle abort or a start-up with a robot away from home, once the robots are clear). Watch `PLC_PRG.fbCell` outputs (state, error, robot/op/zone of the error).\n\n");
            let errs = enum_values(proj, "E_CellError");
            if !errs.is_empty() {
                o.push_str("| E_CellError | Value |\n|---|---|\n");
                for (n, v) in errs {
                    let _ = writeln!(o, "| {n} | {v} |");
                }
            }
        }
    }
    for p in &m.projects {
        let Some(sc) = &p.symbol_config else {
            continue;
        };
        let _ = writeln!(
            o,
            "\n## OPC UA ({})\n\nSymbol Configuration with OPC UA support; the runtime's OPC UA server (port {}) publishes, read-only, below `ns=4;s=|var|<device type name>.Application.` (browse for the application node; the prefix is the runtime's device name, e.g. `CODESYS Control for Linux SL`):\n",
            p.name, p.runtime.opcua_port
        );
        for x in &sc.opc_ua_paths {
            let _ = writeln!(o, "- `{x}`");
        }
        o.push_str("\nExported: ");
        let parts: Vec<String> = sc
            .symbols
            .iter()
            .map(|x| {
                format!(
                    "`{}{}` {}{}",
                    x.signature,
                    x.variable
                        .as_ref()
                        .map(|v| format!(".{v}"))
                        .unwrap_or_else(|| " (all)".into()),
                    x.access,
                    if x.optional { " (optional)" } else { "" }
                )
            })
            .collect();
        o.push_str(&parts.join(", "));
        o.push('\n');
    }
    let _ = writeln!(
        o,
        "\n## Build routes\n\n1. **MCP**: give an agent `MCP_PROMPT.md` (Windows CODESYS + MCP server).\n2. **Manual**: follow the tables above; paste each declaration file into the declaration part and each `_Body.st` into the implementation part.\n\n## Download and run (docker simulation)\n\nStart the robot runtimes first (`docker compose -f docker-compose.yml -f <out>/docker/docker-compose.robots.yml up -d`), download each robot simulator project to its runtime, then the head PLC project to `codesys-master`. Set `PLC_PRG.bStart` (or keep `bAutoRun`).\n\n## Known limitations\n\n- Zones are logical ordering mutexes derived from the behaviour tree, on a standard (non-safety) PLC. They are not a substitute for safety-rated workspace monitoring.\n- After a mid-cycle abort, or a start-up with any robot away from home, the cell waits in recovery for `bRecoveryConfirm` before blind sequential homing; the cycle restarts from op 1.\n- The IO-mapping CSV import path and device parameter ids should be read back after setting them."
    );
    o
}

pub fn mcp_prompt_md(
    plan: &CellPlan,
    cfg: &Config,
    projects: &[PlcProject],
    m: &Manifest,
) -> String {
    let mut o = String::new();
    let names: Vec<&str> = m.projects.iter().map(|p| p.name.as_str()).collect();
    let _ = writeln!(
        o,
        "# Task: build the CODESYS projects for cell `{}`\n",
        plan.cell_id
    );
    let _ = writeln!(
        o,
        "You are an automation engineer agent with access to a CODESYS MCP server (CODESYS {} on Windows). Build {} CODESYS project(s) - {} - exactly as described in `project.json` (in this directory). All PLC code is already written and was type-checked with the trust-platform compiler; your job is project creation, hardware configuration, code insertion, IO mapping, tasks and a clean build. Do **not** modify any existing CODESYS project; create new project files.\n",
        cfg.codesys.ide_version,
        names.len(),
        names
            .iter()
            .map(|n| format!("`{n}`"))
            .collect::<Vec<_>>()
            .join(", ")
    );
    o.push_str("## Inputs\n\n- `project.json`: device trees with exact DeviceIDs `(type, id, version)` and parameter ids, IO mappings, tasks, libraries, objects in creation order, steps, acceptance criteria. **It is the source of truth.**\n- `codesys/head/` and `codesys/robots/<ns>/`: one file per object: `DUT/<Name>.st` and `GVL/<Name>.st` (declaration only), `POU/<Name>.st` (declaration) + `POU/<Name>_Body.st` (implementation).\n- `codesys/*/io_mapping.csv`: fallback IO mapping import (CoDeSys Mapping Export V1.2).\n- `PROJECT.md`: the same information as tables, for humans.\n\n");
    o.push_str("## 0. Before you start\n\n1. List the MCP server's tools and read their parameter schemas. Never guess tool or parameter names.\n2. Confirm the CODESYS version and that the scripting engine is available.\n3. Check the prerequisites below are installed in the device repository (search by the DeviceIDs). If the PN device description (type 83) is missing, STOP and ask the human to run the manual step.\n\n");
    for p in &m.prerequisites {
        let _ = writeln!(
            o,
            "- `{}`: {} -> `({}, '{}', '{}')`",
            p.id,
            p.file
                .clone()
                .or(p.how.map(str::to_string))
                .unwrap_or_default(),
            p.provides.ty,
            p.provides.id,
            p.provides.version
        );
    }
    o.push_str(
        "\n## 1. Capability mapping\n\n| Step | Codesys-MCP-Master (phobicdotno) | luke-harriman Codesys-MCP | codesys-mcp-toolkit (johannesPettersson80) |\n|---|---|---|---|\n\
| create project | `create_project` (device by repository name) | `create_project` | `create_project` (Standard template only) |\n\
| device tree | `add_device`, `plug_device` | `add_device` | HUMAN |\n\
| device parameters | `set_device_parameter` (+ read back) | `set_device_parameter` (experimental) / `eval_python` | HUMAN |\n\
| libraries | `add_library` | `add_library` | HUMAN |\n\
| DUT / GVL | `create_dut`, `create_gvl` + set declaration | `create_dut`, `create_gvl` | HUMAN (or PLCopen import) |\n\
| POU code | `create_pou` + `set_pou_code` | `create_pou` + `set_pou_code` | `create_pou` + `set_pou_code(declarationCode, implementationCode)` |\n\
| tasks | `create_task`, `configure_task`, `add_pou_to_task` | `eval_python` | HUMAN |\n\
| IO mapping | per channel or `import_io_mappings_csv` | `map_io_channel` | HUMAN |\n\
| build | `compile_project` + messages | `compile_project`, `get_compile_messages` | `compile_project` |\n\n\
Prefer Codesys-MCP-Master. Where a step is HUMAN for your server, collect the exact instructions from `PROJECT.md` and hand them to the human in your final report.\n\n",
    );
    o.push_str("## 2. Procedure (per project in `projects[]`, head PLC first)\n\n");
    o.push_str("1. **Create** the project `<name>.project` with device `CODESYS Control for Linux SL` `(4102, '0000 0005', '4.20.0.0')`, ST, Standard template. Delete nothing else the template creates except replacing `PLC_PRG` (see 4).\n");
    o.push_str("2. **Device tree** in `device_tree` order: add each child under its parent with the exact DeviceID; use the node `name` as the object name (it is referenced by IO mapping and tasks, e.g. `PN_Controller.CommCycle`). For PROFINET devices, plug/ensure the modules in `slots[]` (slot number, module id, object name). Set every `parameters[]` entry by id; `member` is the path of a sub-element inside a struct parameter, with `.` separating nesting levels (e.g. parameter 512, member `Identification.StationName`). Read every parameter back and compare. Checkpoint: list the device tree.\n");
    if plan.robots.iter().any(|r| !r.addr.safety_module) {
        o.push_str("   SIMULATION ONLY (`safety_module = false`): a slot with `\"empty\": true` (slot 1 of a KUKA device on DAP `DIM 3`) must hold no module: unplug the module the device came with there (FDIO64; e.g. `unplug_device`) and check that the slot shows `<Empty>`. Do not plug FDIO64.\n");
    }
    o.push_str("3. **Libraries**: add those with `mode: ensure`; verify that the `auto` ones are present after adding the devices.\n");
    o.push_str("4. **Objects** in `objects[]` order under `Application`: DUTs and GVLs get the declaration file content as their only text. POUs: create with the given `pou_type` and language ST, then set the declaration part to the `declaration` file content and the implementation part to the `implementation` file content - byte-exact, both parts in one call if possible (some servers clear an omitted part). `PLC_PRG` already exists: replace both parts. Checkpoint: list the objects.\n");
    o.push_str("5. **Tasks**: `tasks[]`. `MainTask` cyclic with the given interval/priority and only `PLC_PRG`. The PROFINET tasks are normally created by the PN stack: verify interval, priority and POU; create them only if missing. Set the bus cycle task as given.\n");
    o.push_str("6. **IO mapping**: for every `slots[].io` entry map the channel (`param_id`, `channel`, `sub`) to `variable` ('Map to existing variable'). If your server cannot do this per channel, import `io_mapping_csv`. Read back and compare.\n");
    o.push_str("7. **Build**: 0 errors required. On errors, report the message list verbatim; do not edit generated code except for an obvious, minimal dialect fix, which you must report.\n");
    if m.projects.iter().any(|p| p.symbol_config.is_some()) {
        o.push_str("   **Symbol configuration** (a project with `symbol_config`, step `symbol_config` after the build): add a Symbol Configuration with OPC UA support to the application (e.g. `create_symbol_config(supportOpcUa=true)`, `set_symbol_config_settings(contentFeatureFlags=[SupportOPCUA])`); set each `symbols[]` entry's access (`set_symbol_access` for a `variable`, `set_signature_access_bulk` for a whole signature; an `optional` one may fail, report it as a warning); build; then list the configured symbols (`list_configured_symbols`) and check every `require[]` entry is exported readable.\n");
    }
    o.push_str("8. **Save** and continue with the next project.\n\n");
    let k1 = plan.robots.first().is_none_or(|r| r.addr.safety_module);
    let (kid, kver) = if k1 {
        (
            project_json::KUKA_GSDML_ID,
            project_json::KUKA_GSDML_VERSION,
        )
    } else {
        (
            project_json::KUKA_GSDML_ID_DIM3,
            project_json::KUKA_GSDML_VERSION_DIM3,
        )
    };
    o.push_str("## 3. ScriptEngine fallback (IronPython 2.7, e.g. via `eval_python`) - verify each call against your CODESYS version\n\n```python\nproj = projects.primary\ndev = proj.find('Device', False)[0]\ndev.add('Ethernet', 110, '0000 0002', '4.2.0.0')\neth = proj.find('Ethernet', True)[0]\neth.add('PN_Controller', 80, '0000 0002', '4.7.1.0')\npnc = proj.find('PN_Controller', True)[0]\n");
    let _ = writeln!(o, "pnc.add('kuka_robi1', 81, '{kid}', '{kver}')");
    o.push_str("# modules: plug into the empty slot children of the KUKA device (module id is the last argument)\n# parameters: for c in node.connectors: for p in c.host_parameters: if p.id == 512: ...\n# io mapping: p.io_mapping.variable = 'Application.GVL_IO.aVassInputData_R1'\napp = proj.find('Application', True)[0]\ngvl = app.create_gvl('GVL_Cell'); gvl.textual_declaration.replace(open(r'...GVL_Cell.st').read())\nfb = app.create_pou('FB_Cell', PouType.FunctionBlock)\nfb.textual_declaration.replace(DECL); fb.textual_implementation.replace(BODY)\napp.build()\n```\n\n");
    o.push_str("## 4. Acceptance and report\n\nFor each project: build with 0 errors, all `acceptance.objects` present, all `acceptance.devices` present with the parameter values read back. Finish with a JSON report:\n\n```json\n{\"projects\": [{\"name\": \"...\", \"file\": \"...\", \"built\": true, \"errors\": [], \"warnings\": [], \"deviations\": [], \"human_steps\": []}]}\n```\n\n");
    let _ = writeln!(
        o,
        "## 5. Context you may need\n\n- Coordination: each robot runs its whole op list in production Folge {} and requests interlock zones (REQUEST bits, robot -> PLC bytes {}-{}) before ops that depend on other robots; the head PLC grants them (GRANT bits, PLC -> robot bytes {}-{}) in the planned ticket order. Op index: robot -> PLC bytes {}-{}. Plan id: PLC -> robot bytes {}-{}.\n- Zones:\n",
        cfg.cell.prod_folge,
        cfg.protocol.request_byte,
        cfg.protocol.request_byte + 3,
        cfg.protocol.grant_byte,
        cfg.protocol.grant_byte + 3,
        cfg.protocol.step_byte,
        cfg.protocol.step_byte + 1,
        cfg.protocol.plan_id_byte,
        cfg.protocol.plan_id_byte + 1
    );
    zones_summary(&mut o, plan);
    o.push_str("- Simulation only: zones are logical, not safety-rated.\n");
    let _ = projects;
    o
}
