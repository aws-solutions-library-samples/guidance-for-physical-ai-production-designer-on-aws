//! Generated GVLs: `GVL_Cell` (head PLC tables) and `GVL_Program` (one robot simulator).
//!
//! Schemas: `docs/TEMPLATE_BRIEF.md` §C. Array bounds are literals (`*_DIM = max(1, n)`,
//! dummy rows are zero) so the same text works in CODESYS and in the trust rendering.

use std::fmt::Write as _;

use crate::backend::model::{ObjKind, Origin, PlcObject};
use crate::backend::st_fmt::{
    bool_lit, comment, dword_hex, real_lit, string_lit, time_lit, word_hex, word_lit,
};
use crate::config::GrantPolicy;
use crate::config::{Config, HomeStrategy, JobNumber, vw_ks24 as vw};
use crate::error::{DiagCode, Error, Result};
use crate::ir::{
    CellPlan, ERR_PLAN_MISMATCH, ERR_UNKNOWN_FOLGE, OpKind, Robot, WARN_START_DEVIATION,
};

const GEN: &str = concat!("bt2plc ", env!("CARGO_PKG_VERSION"));

fn line(out: &mut String, name: &str, ty: &str, init: &str, note: &str) {
    let mut s = format!("    {name:<24}: {ty}");
    if !init.is_empty() {
        s.push_str(" := ");
        s.push_str(init);
    }
    s.push(';');
    if !note.is_empty() {
        s = format!("{s:<64}(* {} *)", comment(note));
    }
    out.push_str(&s);
    out.push('\n');
}

fn banner(out: &mut String, title: &str) {
    out.push_str(
        "\n    (* ========================================================================\n",
    );
    let _ = writeln!(out, "       {}", comment(title));
    out.push_str(
        "       ======================================================================== *)\n",
    );
}

fn list<T>(items: &[T], f: impl Fn(&T) -> String) -> String {
    format!("[{}]", items.iter().map(f).collect::<Vec<_>>().join(", "))
}

fn ms(s: f64) -> u64 {
    (s * 1000.0).round().max(0.0) as u64
}

/// Head PLC constant tables.
pub fn gvl_cell(plan: &CellPlan, cfg: &Config) -> PlcObject {
    let nr = plan.robots.len();
    let nz = plan.zones.len();
    let ops_in_order: Vec<usize> = plan
        .robots
        .iter()
        .flat_map(|r| r.ops.iter().copied())
        .collect();
    let n_preds: usize = plan.ops.iter().map(|o| o.permit_preds.len()).sum();
    let n_tickets: usize = plan.zones.iter().map(|z| z.tickets.len()).sum();
    let p = &cfg.protocol;
    let t = &cfg.timing;
    let mut o = String::new();
    let _ = writeln!(o, "(*\n * GVL_Cell - generated by {GEN} - DO NOT EDIT");
    let _ = writeln!(
        o,
        " * Plan   : {} (cell {})",
        comment(&plan.tree_id),
        comment(&plan.cell_id)
    );
    let _ = writeln!(
        o,
        " * Grants : {}",
        if plan.grant_policy == GrantPolicy::Planned {
            "planned ticket order"
        } else {
            "FCFS (BT order NOT enforced)"
        }
    );
    for z in &plan.zones {
        let members: Vec<String> = z
            .tickets
            .iter()
            .map(|t| {
                format!(
                    "{}#{} {}",
                    plan.robots[t.robot].addr.tag, t.op_index, plan.ops[t.op].operation_id
                )
            })
            .collect();
        let _ = writeln!(o, " * {:<6} : {}", z.name, comment(&members.join(" > ")));
    }
    if n_preds > 0 {
        let _ = writeln!(
            o,
            " * Permit : {n_preds} cross-robot dependencies beyond the zone capacity (bit 31)"
        );
    }
    o.push_str(" *)\n{attribute 'qualified_only'}\nVAR_GLOBAL CONSTANT");
    banner(&mut o, "DIMENSIONS (array bounds are literals; *_DIM >= 1)");
    line(&mut o, "N_ROBOTS", "INT", &nr.to_string(), "");
    line(&mut o, "N_ZONES", "INT", &nz.to_string(), "");
    line(&mut o, "N_OPS", "INT", &plan.ops.len().to_string(), "");
    line(&mut o, "N_PREDS", "INT", &n_preds.to_string(), "");
    banner(&mut o, "PROTOCOL / TIMING");
    line(
        &mut o,
        "PLAN_ID",
        "WORD",
        &word_hex(plan.plan_id),
        "fold of the plan fingerprint",
    );
    line(
        &mut o,
        "PROD_FOLGE",
        "WORD",
        &word_lit(cfg.cell.prod_folge),
        "default production Folge",
    );
    line(
        &mut o,
        "HOME_FOLGE",
        "WORD",
        &word_lit(cfg.cell.home_folge),
        "blind homing",
    );
    line(
        &mut o,
        "JOB_NUMBER_BYTE",
        "BOOL",
        bool_lit(cfg.cell.job_number == JobNumber::Byte),
        "FALSE: WORD LE bytes 2-3, TRUE: byte 2",
    );
    line(
        &mut o,
        "PROFILE_VW",
        "BOOL",
        bool_lit(p.profile.is_vw()),
        "TRUE: VW KS24 signal map and Folge handshake instead of the simulator telegram",
    );
    let gp = if plan.grant_policy == GrantPolicy::Planned {
        "GP_PLANNED"
    } else {
        "GP_FCFS"
    };
    line(
        &mut o,
        "GRANT_POLICY",
        "E_GrantPolicy",
        &format!("E_GrantPolicy.{gp}"),
        "",
    );
    line(
        &mut o,
        "HOME_SEQUENTIAL",
        "BOOL",
        bool_lit(cfg.cell.home_strategy == HomeStrategy::Sequential),
        "",
    );
    line(
        &mut o,
        "AUTO_RUN",
        "BOOL",
        bool_lit(cfg.cell.auto_run),
        "start the next cycle automatically",
    );
    line(
        &mut o,
        "STEP_BYTE",
        "INT",
        &p.step_byte.to_string(),
        "robot -> PLC, WORD LE op index",
    );
    line(
        &mut o,
        "REQ_BYTE",
        "INT",
        &p.request_byte.to_string(),
        "robot -> PLC, DWORD LE zone requests",
    );
    line(
        &mut o,
        "GRANT_BYTE",
        "INT",
        &p.grant_byte.to_string(),
        "PLC -> robot, DWORD LE zone grants",
    );
    line(
        &mut o,
        "PLAN_ID_BYTE",
        "INT",
        &p.plan_id_byte.to_string(),
        "PLC -> robot, WORD LE plan id",
    );
    line(
        &mut o,
        "PERMIT_MASK",
        "DWORD",
        &dword_hex(crate::ir::PERMIT_BIT),
        "bit 31: permit predecessors",
    );
    line(
        &mut o,
        "T_RESET_PULSE",
        "TIME",
        &time_lit(p.reset_pulse_ms.into()),
        "",
    );
    line(
        &mut o,
        "T_START_PULSE",
        "TIME",
        &time_lit(p.start_pulse_ms.into()),
        "",
    );
    line(
        &mut o,
        "T_STOP_PULSE",
        "TIME",
        &time_lit(p.stop_pulse_ms.into()),
        "",
    );
    line(
        &mut o,
        "T_HANDSHAKE",
        "TIME",
        &time_lit(p.handshake_timeout_ms.into()),
        "",
    );
    line(
        &mut o,
        "T_BRINGUP_LIMIT",
        "TIME",
        &time_lit(p.bringup_limit_ms.into()),
        "safety enable: PROFINET connection set-up",
    );
    line(
        &mut o,
        "T_MISMATCH_DEBOUNCE",
        "TIME",
        &time_lit(p.mismatch_debounce_ms.into()),
        "",
    );
    line(
        &mut o,
        "T_STOP_DEBOUNCE",
        "TIME",
        &time_lit(p.stop_debounce_ms.into()),
        "job running: ProgRunning and ProgFinished low this long = robot stopped",
    );
    line(
        &mut o,
        "T_CYCLE_PAUSE",
        "TIME",
        &time_lit(p.cycle_pause_ms.into()),
        "",
    );
    line(
        &mut o,
        "T_START_LIMIT",
        "TIME",
        &time_lit(p.start_limit_ms.into()),
        "",
    );
    line(
        &mut o,
        "T_ABORT_LIMIT",
        "TIME",
        &time_lit(p.abort_limit_ms.into()),
        "",
    );
    let home_limit = ms(t.home_limit_s());
    line(&mut o, "T_HOME_LIMIT", "TIME", &time_lit(home_limit), "");

    banner(
        &mut o,
        "VW KS24 SIGNAL INDICES (used when PROFILE_VW; $IN/$OUT index, 1-based)",
    );
    for (name, v, what) in [
        ("VW_READY_OUT", vw::READY_OUT, "O_R_Bereit"),
        ("VW_RK100_OUT", vw::RK100_OUT, "O_R_RK100 safety circuit"),
        ("VW_AUTO_OUT", vw::AUTO_OUT, "O_R_Auto"),
        ("VW_ESTOP_OUT", vw::ESTOP_OUT, "O_R_Notaus"),
        ("VW_END_OUT", vw::FOLGE_END_OUT, "O_R_F_ENDE / LPKT"),
        ("VW_PF0_OUT", vw::PF0_OUT, "O_R_PFO home position"),
        (
            "VW_STEP_OUT",
            vw::STEP_OUT,
            "P_PktNr_SPS op index (16 bits)",
        ),
        ("VW_REL_OUT", vw::RELEASE_OUT, "interlock releases A41-56"),
        ("VW_REQ_OUT", vw::REQUEST_OUT, "interlock requests A81-96"),
        (
            "VW_ERR_OUT",
            vw::ERROR_OUT,
            "VW_FEH_BIN_A error code (8 bits)",
        ),
        ("VW_DRIVES_IN", vw::DRIVES_IN, "I_R_Ant_Ein"),
        ("VW_SRB_IN", vw::SRB_IN, "I_R_SRB Folge start"),
        ("VW_RESET_IN", vw::RESET_IN, "I_R_Quit_St acknowledge"),
    ] {
        line(&mut o, name, "INT", &v.to_string(), what);
    }
    // Only meaningful with PROFILE_VW; zero in profile sim so the table cannot be mistaken
    // for an active mapping.
    let il = if p.profile.is_vw() {
        crate::ir::interlock_map(plan, cfg)
    } else {
        vec![vec![0u8; nz]; nr]
    };
    let nzd = nz.max(1);
    let mut rows: Vec<String> = Vec::new();
    for r in 0..nr {
        for z in 0..nzd {
            rows.push(
                il.get(r)
                    .and_then(|v| v.get(z))
                    .copied()
                    .unwrap_or(0)
                    .to_string(),
            );
        }
    }
    line(
        &mut o,
        "anInterlock",
        &format!("ARRAY[1..{}] OF INT", nr * nzd),
        &format!("[{}]", rows.join(",")),
        &format!("robot r, zone z -> VW interlock 1..16 (0 = not a member): index (r-1)*{nzd}+z"),
    );

    banner(&mut o, "ROBOTS (index = BT order)");
    line(
        &mut o,
        "asRobotTag",
        &format!("ARRAY[1..{nr}] OF STRING(16)"),
        &list(&plan.robots, |r| string_lit(&r.addr.tag, 16)),
        "",
    );
    line(
        &mut o,
        "asRobotNs",
        &format!("ARRAY[1..{nr}] OF STRING(32)"),
        &list(&plan.robots, |r| string_lit(&r.ns, 32)),
        "",
    );
    line(
        &mut o,
        "abRobotActive",
        &format!("ARRAY[1..{nr}] OF BOOL"),
        &list(&plan.robots, |r| bool_lit(!r.idle).to_string()),
        "",
    );
    line(
        &mut o,
        "abSafetyBypass",
        &format!("ARRAY[1..{nr}] OF BOOL"),
        &list(&plan.robots, |r| bool_lit(r.addr.safety_bypass).to_string()),
        "SIMULATION ONLY: PROFIsafe slot-1 bits not required ([[robot]] safety_bypass)",
    );
    line(
        &mut o,
        "awRobotProdFolge",
        &format!("ARRAY[1..{nr}] OF WORD"),
        &list(&plan.robots, |r| word_lit(r.addr.prod_folge)),
        "",
    );
    let mut first = Vec::new();
    let mut next = 1usize;
    for r in &plan.robots {
        first.push(if r.ops.is_empty() { 0 } else { next });
        next += r.ops.len();
    }
    line(
        &mut o,
        "anRobotFirstOp",
        &format!("ARRAY[1..{nr}] OF INT"),
        &list(&first, |v| v.to_string()),
        "op k of robot r: aOps[anRobotFirstOp[r] + k - 1]",
    );
    line(
        &mut o,
        "anRobotOpCount",
        &format!("ARRAY[1..{nr}] OF INT"),
        &list(&plan.robots, |r| r.ops.len().to_string()),
        "",
    );

    banner(
        &mut o,
        "ZONES - tickets of zone z: aTickets[anZoneFirst[z] .. anZoneFirst[z] + anZoneCount[z] - 1]",
    );
    let zd = nz.max(1);
    let (names, firsts, counts) = if nz == 0 {
        (
            vec!["''".to_string()],
            vec!["0".to_string()],
            vec!["0".to_string()],
        )
    } else {
        let mut f = Vec::new();
        let mut acc = 1;
        for z in &plan.zones {
            f.push(acc.to_string());
            acc += z.tickets.len();
        }
        (
            plan.zones.iter().map(|z| string_lit(&z.name, 8)).collect(),
            f,
            plan.zones
                .iter()
                .map(|z| z.tickets.len().to_string())
                .collect(),
        )
    };
    line(
        &mut o,
        "asZoneName",
        &format!("ARRAY[1..{zd}] OF STRING(8)"),
        &format!("[{}]", names.join(", ")),
        "",
    );
    line(
        &mut o,
        "anZoneFirst",
        &format!("ARRAY[1..{zd}] OF INT"),
        &format!("[{}]", firsts.join(", ")),
        "",
    );
    line(
        &mut o,
        "anZoneCount",
        &format!("ARRAY[1..{zd}] OF INT"),
        &format!("[{}]", counts.join(", ")),
        "",
    );
    let td = n_tickets.max(1);
    let _ = writeln!(
        o,
        "    {:<24}: ARRAY[1..{td}] OF ST_Ticket := [",
        "aTickets"
    );
    let mut rows = Vec::new();
    for z in &plan.zones {
        for (k, t) in z.tickets.iter().enumerate() {
            let note = if k == 0 {
                format!("{} ", z.name)
            } else {
                String::new()
            };
            rows.push((
                format!("(nRobot := {}, nOp := {})", t.robot + 1, t.op_index),
                format!(
                    "{note}{} #{} {}",
                    plan.robots[t.robot].addr.tag, t.op_index, plan.ops[t.op].operation_id
                ),
            ));
        }
    }
    if rows.is_empty() {
        rows.push(("(nRobot := 0, nOp := 0)".into(), "no zones".into()));
    }
    push_rows(&mut o, &rows);

    banner(
        &mut o,
        "OPS - op k of robot r: aOps[anRobotFirstOp[r] + k - 1]",
    );
    let _ = writeln!(
        o,
        "    (* tLimit = {} x tExpected + {} s ; tZoneDeadline = {} x ASAP grant + ({} + {}) s x depth + {} s *)",
        t.watchdog_factor,
        t.watchdog_margin_s,
        t.watchdog_factor,
        t.watchdog_margin_s,
        t.hop_latency_s,
        t.zone_wait_margin_s
    );
    let od = plan.ops.len().max(1);
    let _ = writeln!(o, "    {:<24}: ARRAY[1..{od}] OF ST_OpInfo := [", "aOps");
    let mut rows = Vec::new();
    let mut pred_first = 1usize;
    for &oi in &ops_in_order {
        let op = &plan.ops[oi];
        let (pf, pc) = if op.permit_preds.is_empty() {
            (0, 0)
        } else {
            let f = pred_first;
            pred_first += op.permit_preds.len();
            (f, op.permit_preds.len())
        };
        rows.push((
            format!(
                "(nRobot := {}, nOp := {}, dwZoneMask := {}, nPredFirst := {pf}, nPredCount := {pc}, tExpected := {}, tLimit := {}, tZoneDeadline := {}, sName := {})",
                op.robot + 1,
                op.index,
                dword_hex(op.zone_mask),
                time_lit(op.expected_ms),
                time_lit(op.limit_ms),
                time_lit(op.zone_deadline_ms),
                string_lit(&op.operation_id, 32)
            ),
            format!("{} #{} {}", plan.robots[op.robot].addr.tag, op.index, op.operation_id),
        ));
    }
    push_rows(&mut o, &rows);

    banner(
        &mut o,
        "PERMIT PREDECESSORS - op preds: aPreds[nPredFirst .. nPredFirst + nPredCount - 1]",
    );
    let pd = n_preds.max(1);
    let _ = writeln!(o, "    {:<24}: ARRAY[1..{pd}] OF ST_Ticket := [", "aPreds");
    let mut rows = Vec::new();
    for &oi in &ops_in_order {
        let op = &plan.ops[oi];
        for &u in &op.permit_preds {
            let pu = &plan.ops[u];
            rows.push((
                format!("(nRobot := {}, nOp := {})", pu.robot + 1, pu.index),
                format!(
                    "{} #{} {} needs {} #{} {}",
                    plan.robots[op.robot].addr.tag,
                    op.index,
                    op.operation_id,
                    plan.robots[pu.robot].addr.tag,
                    pu.index,
                    pu.operation_id
                ),
            ));
        }
    }
    if rows.is_empty() {
        rows.push((
            "(nRobot := 0, nOp := 0)".into(),
            "no permit predecessors".into(),
        ));
    }
    push_rows(&mut o, &rows);
    o.push_str("END_VAR\n");
    PlcObject {
        name: "GVL_Cell".into(),
        kind: ObjKind::Gvl,
        decl: o,
        body: None,
        origin: Origin::Generated,
    }
}

fn push_rows(o: &mut String, rows: &[(String, String)]) {
    for (i, (r, note)) in rows.iter().enumerate() {
        let sep = if i + 1 < rows.len() { "," } else { "" };
        let _ = writeln!(o, "        {r}{sep}    (* {} *)", comment(note));
    }
    o.push_str("    ];\n");
}

fn joint_deg(r: &Robot, q: &[f64; 6]) -> [f64; 6] {
    let mut out = [0.0; 6];
    for i in 0..6 {
        out[i] = f64::from(r.addr.joint_sign[i]) * q[i].to_degrees() + r.addr.joint_offset_deg[i];
    }
    out
}

/// Robot simulator program table for robot `ri`.
pub fn gvl_program(plan: &CellPlan, cfg: &Config, ri: usize) -> Result<PlcObject> {
    let r = &plan.robots[ri];
    let p = &cfg.protocol;
    let tol = cfg.robot_sim.decimate_tol_deg;
    let kept: Vec<Vec<usize>> = r
        .ops
        .iter()
        .map(|&o| {
            plan.ops[o]
                .trajectory
                .as_ref()
                .map_or(Vec::new(), |t| crate::ir::decimate::keep(t, tol))
        })
        .collect();
    let original: usize = r
        .ops
        .iter()
        .map(|&o| {
            plan.ops[o]
                .trajectory
                .as_ref()
                .map_or(0, |t| t.waypoints.len())
        })
        .sum();
    let total: usize = kept.iter().map(Vec::len).sum();
    if total > cfg.robot_sim.max_waypoints_per_robot as usize || total > 32000 {
        return Err(Error::plan(
            DiagCode::E022,
            None,
            format!(
                "robot {}: {total} waypoints exceed robot_sim.max_waypoints_per_robot = {} (hard cap 32000)",
                r.ns, cfg.robot_sim.max_waypoints_per_robot
            ),
        ));
    }
    let mut o = String::new();
    let _ = writeln!(o, "(*\n * GVL_Program - generated by {GEN} - DO NOT EDIT");
    let _ = writeln!(
        o,
        " * Robot program of {} ({}) for plan {} (cell {})",
        comment(&r.ns),
        comment(&r.addr.tag),
        comment(&plan.tree_id),
        comment(&plan.cell_id)
    );
    let _ = writeln!(
        o,
        " * Angles in degrees (KUKA A1..A6 after joint sign/offset), times in seconds from op start."
    );
    if total != original {
        let _ = writeln!(
            o,
            " * Waypoints decimated from {original} to {total} (tolerance {tol} deg)."
        );
    }
    o.push_str(" *)\n{attribute 'qualified_only'}\nVAR_GLOBAL CONSTANT");
    banner(&mut o, "IDENTITY / PROTOCOL");
    line(
        &mut o,
        "ROBOT_TAG",
        "STRING(16)",
        &string_lit(&r.addr.tag, 16),
        "",
    );
    line(&mut o, "ROBOT_NS", "STRING(32)", &string_lit(&r.ns, 32), "");
    line(
        &mut o,
        "ROBOT_INDEX",
        "WORD",
        &word_lit((ri + 1) as u16),
        "",
    );
    line(
        &mut o,
        "PLAN_ID",
        "WORD",
        &word_hex(plan.plan_id),
        "must match the head PLC",
    );
    line(
        &mut o,
        "PROD_FOLGE",
        "WORD",
        &word_lit(r.addr.prod_folge),
        "",
    );
    line(
        &mut o,
        "HOME_FOLGE",
        "WORD",
        &word_lit(cfg.cell.home_folge),
        "",
    );
    line(
        &mut o,
        "JOB_NUMBER_BYTE",
        "BOOL",
        bool_lit(cfg.cell.job_number == JobNumber::Byte),
        "",
    );
    line(&mut o, "STEP_BYTE", "INT", &p.step_byte.to_string(), "");
    line(&mut o, "REQ_BYTE", "INT", &p.request_byte.to_string(), "");
    line(&mut o, "GRANT_BYTE", "INT", &p.grant_byte.to_string(), "");
    line(
        &mut o,
        "PLAN_ID_BYTE",
        "INT",
        &p.plan_id_byte.to_string(),
        "",
    );
    line(
        &mut o,
        "R_TASK_S",
        "REAL",
        &real_lit(f64::from(cfg.codesys.device_main_task_ms) / 1000.0),
        "device MainTask interval",
    );
    line(
        &mut o,
        "R_HOME_S",
        "REAL",
        &real_lit(cfg.timing.home_return_time_s),
        "blind home duration",
    );
    line(
        &mut o,
        "R_AT_HOME_TOL_DEG",
        "REAL",
        &real_lit(cfg.robot_sim.at_home_tol_deg),
        "",
    );
    line(
        &mut o,
        "R_START_TOL_DEG",
        "REAL",
        &real_lit(cfg.robot_sim.start_tol_deg),
        "",
    );
    for (name, code) in [
        ("ERR_UNKNOWN_FOLGE", ERR_UNKNOWN_FOLGE),
        ("ERR_PLAN_MISMATCH", ERR_PLAN_MISMATCH),
        ("WARN_START_DEVIATION", WARN_START_DEVIATION),
    ] {
        line(&mut o, name, "WORD", &format!("WORD#16#{code:04X}"), "");
    }
    banner(&mut o, "PROGRAM");
    line(&mut o, "N_OPS", "INT", &r.ops.len().to_string(), "");
    line(&mut o, "N_WP", "INT", &total.to_string(), "");
    let home = joint_deg(r, &r.home_pose_rad);
    line(
        &mut o,
        "arHomeDeg",
        "ARRAY[1..6] OF REAL",
        &list(&home, |v| real_lit(*v)),
        "",
    );
    let od = r.ops.len().max(1);
    let _ = writeln!(o, "    {:<24}: ARRAY[1..{od}] OF ST_OpDef := [", "aOps");
    let mut rows = Vec::new();
    let mut wp = 1usize;
    for (k, &oi) in r.ops.iter().enumerate() {
        let op = &plan.ops[oi];
        let (f, l, blind) = match &op.trajectory {
            Some(_) => {
                let f = wp;
                wp += kept[k].len();
                (f, wp - 1, false)
            }
            None => (0, 0, true),
        };
        rows.push((
            format!(
                "(sName := {}, nFirstWp := {f}, nLastWp := {l}, dwZoneMask := {}, tDelay := {}, tHold := {}, rDelay_s := {}, rHold_s := {}, rVelScale := {}, bBlindHome := {})",
                string_lit(&op.operation_id, 32),
                dword_hex(op.zone_mask),
                time_lit(op.start_delay_ms),
                time_lit(op.hold_ms),
                real_lit(op.start_delay_ms as f64 / 1000.0),
                real_lit(op.hold_ms as f64 / 1000.0),
                real_lit(op.velocity_scale),
                bool_lit(blind)
            ),
            format!(
                "#{} {}{}",
                op.index,
                op.operation_id,
                match &op.kind {
                    OpKind::Execute { operation_type } => format!(" ({operation_type})"),
                    OpKind::MoveHome => " (home)".into(),
                }
            ),
        ));
    }
    if rows.is_empty() {
        rows.push((
            "(sName := '', nFirstWp := 0, nLastWp := 0, dwZoneMask := DWORD#16#00000000, tDelay := T#0MS, tHold := T#0MS, rDelay_s := 0.0000, rHold_s := 0.0000, rVelScale := 1.0000, bBlindHome := FALSE)".into(),
            "idle robot: no ops".into(),
        ));
    }
    push_rows(&mut o, &rows);
    let wd = total.max(1);
    let _ = writeln!(o, "    {:<24}: ARRAY[1..{wd}] OF ST_Waypoint := [", "aWp");
    let mut rows = Vec::new();
    for (ki, &oi) in r.ops.iter().enumerate() {
        let op = &plan.ops[oi];
        let Some(t) = &op.trajectory else { continue };
        for (k, w) in kept[ki].iter().map(|&i| &t.waypoints[i]).enumerate() {
            let q = joint_deg(r, &w.q_rad);
            let note = if k == 0 {
                format!(
                    "op {} {} - {}",
                    op.index,
                    op.operation_id,
                    t.key.as_deref().unwrap_or("inline")
                )
            } else {
                String::new()
            };
            rows.push((
                format!(
                    "(rT := {}, rA1 := {}, rA2 := {}, rA3 := {}, rA4 := {}, rA5 := {}, rA6 := {})",
                    real_lit(w.t_s),
                    real_lit(q[0]),
                    real_lit(q[1]),
                    real_lit(q[2]),
                    real_lit(q[3]),
                    real_lit(q[4]),
                    real_lit(q[5])
                ),
                note,
            ));
        }
    }
    if rows.is_empty() {
        rows.push(("(rT := 0.0000, rA1 := 0.0000, rA2 := 0.0000, rA3 := 0.0000, rA4 := 0.0000, rA5 := 0.0000, rA6 := 0.0000)".into(), "no waypoints".into()));
    }
    for (i, (row, note)) in rows.iter().enumerate() {
        let sep = if i + 1 < rows.len() { "," } else { "" };
        if note.is_empty() {
            let _ = writeln!(o, "        {row}{sep}");
        } else {
            let _ = writeln!(o, "        (* {} *)\n        {row}{sep}", comment(note));
        }
    }
    o.push_str("    ];\nEND_VAR\n");
    Ok(PlcObject {
        name: "GVL_Program".into(),
        kind: ObjKind::Gvl,
        decl: o,
        body: None,
        origin: Origin::Generated,
    })
}
