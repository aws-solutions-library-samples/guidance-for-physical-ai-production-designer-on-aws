/// REQUEST bits this robot ever sets.
fn used_mask(f: &Folge) -> u32 {
    f.ops.iter().fold(0, |m, o| m | o.mask)
}

pub fn bt_cell_src(ctx: &Ctx, prod: &Folge, home: &Folge) -> String {
    let n = ctx.cfg.sim.interrupt_no;
    let codes = &ctx.p.protocol.error_codes;
    let mut t = Text::default();
    ctx.header(
        &mut t,
        &format!("bt2krl sim job loop plan {}", ctx.plan_hex()),
    );
    t.raw("DEF BT_CELL()");
    t.indent();
    ctx.banner(&mut t);
    t.comment("Started once in EXT mode ($EXT_START); every job runs inside this loop.");
    t.comment("bt_sps latches BT_START on a ProgStart edge while Ready (job number in BT_JOBNR).");
    t.open(";FOLD INI");
    t.line("BT_RUN=FALSE");
    t.line("BT_ABRT=FALSE");
    t.line(format!("INTERRUPT DECL {n} WHEN BT_ABRT DO BT_ABORT()"));
    t.close(";ENDFOLD");
    t.open("LOOP");
    t.line("WAIT FOR BT_START");
    t.line("BT_START=FALSE");
    t.line(format!("INTERRUPT ON {n}"));
    t.open("SWITCH BT_JOBNR");
    t.open(format!("CASE {}", prod.number));
    t.line(format!("{}()", prod.name()));
    t.dedent();
    t.open(format!("CASE {}", home.number));
    t.line(format!("{}()", home.name()));
    t.dedent();
    t.open("DEFAULT");
    t.line(format!("BT_ECODE={}", codes.unknown_folge));
    t.line("BT_ERR=TRUE");
    t.dedent();
    t.close("ENDSWITCH");
    t.line(format!("INTERRUPT OFF {n}"));
    t.open("IF BT_ABRT THEN");
    t.comment("aborted (interrupt RESUME or an abort guard RETURN): never resume the cycle");
    abort_clear(ctx, &mut t, used_mask(prod));
    t.line("BT_ABRT=FALSE");
    t.close("ENDIF");
    t.close("ENDLOOP");
    t.dedent();
    t.raw("END");
    t.raw("");
    t.raw("DEF BT_ABORT()");
    t.indent();
    t.comment("Stop/Cancel, drives off, E-stop or interpreter stop while a Folge runs:");
    t.comment(
        "brake, STEP := 0, REQUEST := 0, ProgRunning off without ProgFinished, leave the Folge.",
    );
    t.line("BRAKE");
    abort_clear(ctx, &mut t, used_mask(prod));
    t.line("RESUME");
    t.dedent();
    t.raw("END");
    t.finish(ctx.cfg.output.line_ending)
}

fn abort_clear(ctx: &Ctx, t: &mut Text, mask: u32) {
    t.line("BT_STEP=0");
    for b in io::bits(mask) {
        t.line(format!(
            "$OUT[{}]=FALSE ; RELEASE {}",
            ctx.io.req_bit(b),
            ctx.zone_name(b)
        ));
    }
    t.line("BT_FIN=FALSE");
    t.line("BT_RUN=FALSE");
}

pub fn bt_cell_dat(ctx: &Ctx) -> String {
    let mut t = Text::default();
    ctx.header(
        &mut t,
        &format!("bt2krl sim job loop data plan {}", ctx.plan_hex()),
    );
    t.raw("DEFDAT BT_CELL");
    t.indent();
    ctx.banner(&mut t);
    t.dedent();
    t.raw("ENDDAT");
    t.finish(ctx.cfg.output.line_ending)
}

/// Signal names of the 8-bit groups that clear REQUEST (bytes 0..3 of the field).
fn req_groups() -> [&'static str; 4] {
    ["BT_REQ0", "BT_REQ1", "BT_REQ2", "BT_REQ3"]
}

pub fn bt_config_dat(ctx: &Ctx, home: &Folge) -> String {
    let io = &ctx.io;
    let mut t = Text::default();
    t.comment(format!(
        "bt2krl sim: merge into KRC/R1/System/$config.dat (fold USER GLOBALS), robot {} plan {}",
        ctx.p.robot.ns,
        ctx.plan_hex()
    ));
    t.comment("Profile sim. NEVER on a VW KS24 robot: these signals collide with the VW standard.");
    t.open(format!(
        ";FOLD BT2KRL {} {}",
        ascii(&ctx.p.robot.ns).replace(' ', "_"),
        ctx.plan_hex()
    ));
    t.comment(format!(
        "PLC -> robot: telegram byte b bit i = $IN[{} + 8b + i + 1]",
        io.in_base
    ));
    for c in io::COMMANDS {
        t.line(format!(
            "SIGNAL {} $IN[{}] ; [{}].{} {}",
            c.name,
            io.input(c.byte, c.bit),
            c.byte,
            c.bit,
            c.what
        ));
    }
    let job = io.input(io::JOB_BYTE, 0);
    t.line(format!(
        "SIGNAL BT_JOB $IN[{job}] TO $IN[{}] ; job number (Folge)",
        job + io.job_bits() - 1
    ));
    t.line(format!(
        "SIGNAL BT_PLANID $IN[{}] TO $IN[{}] ; PLAN_ID WORD LE",
        io.plan_id,
        io.plan_id + 15
    ));
    t.comment(format!(
        "GRANT bit b = $IN[{}+b] (read per bit in the Folge; bit 31 = permit)",
        io.grant
    ));
    t.comment(format!(
        "robot -> PLC: telegram byte b bit i = $OUT[{} + 8b + i + 1]",
        io.out_base
    ));
    for c in io::STATUS {
        t.line(format!(
            "SIGNAL {} $OUT[{}] ; [{}].{} {}",
            c.name,
            io.output(c.byte, c.bit),
            c.byte,
            c.bit,
            c.what
        ));
    }
    let echo = io.output(io::ECHO_BYTE, 0);
    t.line(format!(
        "SIGNAL BT_ECHO $OUT[{echo}] TO $OUT[{}] ; job echo",
        echo + io.job_bits() - 1
    ));
    t.line(format!(
        "SIGNAL BT_STEP $OUT[{}] TO $OUT[{}] ; op index WORD LE",
        io.step,
        io.step + 15
    ));
    let e = io.output(io::ERROR_BYTE, 0);
    t.line(format!(
        "SIGNAL BT_ERRCODE $OUT[{e}] TO $OUT[{}] ; error code",
        e + 15
    ));
    let w = io.output(io::WARNING_BYTE, 0);
    t.line(format!(
        "SIGNAL BT_WARNCODE $OUT[{w}] TO $OUT[{}] ; warning code",
        w + 15
    ));
    for (i, g) in req_groups().iter().enumerate() {
        let a = io.request + 8 * i as u16;
        t.line(format!(
            "SIGNAL {g} $OUT[{a}] TO $OUT[{}] ; REQUEST byte {i} (cleared by bt_sps)",
            a + 7
        ));
    }
    if ctx.cfg.sim.joint_encoder {
        for i in 0..12u16 {
            let a = io.output(io::JOINT_BYTE + i, 0);
            t.line(format!(
                "SIGNAL BT_JNT{i} $OUT[{a}] TO $OUT[{}] ; A{} {} byte",
                a + 7,
                i / 2 + 1,
                if i % 2 == 0 { "high" } else { "low" }
            ));
        }
    }
    t.comment("Flags shared by bt_sps (submit) and bt_cell / the Folgen (robot interpreter)");
    for b in [
        "BT_START",
        "BT_RUN",
        "BT_FIN",
        "BT_ERR",
        "BT_ACK",
        "BT_ABRT",
        "BT_READY",
        "BT_M_JOB",
        "BT_M_START",
        "BT_M_RESET",
    ] {
        t.line(format!("DECL BOOL {b}=FALSE"));
    }
    for i in ["BT_JOBNR", "BT_PLANL", "BT_ECODE", "BT_WCODE"] {
        t.line(format!("DECL INT {i}=0"));
    }
    let hp = &home.points[0];
    t.line(format!(
        "DECL AXIS BT_HOME={} ; home_pose_deg (AtHome)",
        axis_lit(&Point {
            e: None,
            ..hp.clone()
        })
    ));
    t.close(";ENDFOLD");
    t.finish(ctx.cfg.output.line_ending)
}

pub fn bt_sps_src(ctx: &Ctx) -> String {
    let p = &ctx.p.protocol;
    let timer = ctx.cfg.sim.reset_timer;
    let tol = num(p.at_home_tol_deg);
    let mut t = Text::default();
    ctx.header(
        &mut t,
        &format!("bt2krl sim submit part plan {}", ctx.plan_hex()),
    );
    t.raw("DEF BT_SPS()");
    t.indent();
    t.line("DECL INT BT_Q");
    t.line("DECL BOOL BT_PRUN");
    ctx.banner(&mut t);
    t.comment(
        "Call once per cycle from the LOOP of KRC/R1/System/sps.sub (fold USER PLC): BT_SPS()",
    );
    t.comment("Job handshake as the bt2plc device simulator (FB_VASS_DeviceSimulator).");
    t.open(";FOLD READY AND ABORT");
    t.line(
        "BT_READY=$PERI_RDY AND ($MODE_OP==#EX) AND NOT BT_ERR AND NOT (BT_RUN AND NOT BT_ABRT) AND $ALARM_STOP AND $USER_SAF",
    );
    t.open("IF BT_RUN AND NOT BT_ABRT THEN");
    t.open(
        "IF BT_C_STOP OR BT_C_CANCEL OR NOT $PERI_RDY OR NOT $ALARM_STOP OR ($PRO_STATE1<>#P_ACTIVE) THEN",
    );
    t.line("BT_ABRT=TRUE");
    t.close("ENDIF");
    t.close("ENDIF");
    t.close(";ENDFOLD");
    t.open(";FOLD JOB HANDSHAKE");
    t.open("IF BT_C_JOBREQ AND NOT BT_M_JOB AND BT_READY THEN");
    t.line("BT_JOBNR=BT_JOB");
    t.line("BT_PLANL=BT_PLANID");
    t.line("BT_ACK=TRUE");
    t.line("BT_FIN=FALSE");
    t.close("ENDIF");
    t.open("IF NOT BT_C_JOBREQ THEN");
    t.line("BT_ACK=FALSE");
    t.close("ENDIF");
    t.line("BT_M_JOB=BT_C_JOBREQ");
    t.open("IF BT_C_START AND NOT BT_M_START AND BT_READY AND (BT_JOBNR<>0) THEN");
    t.line("BT_START=TRUE");
    t.close("ENDIF");
    t.line("BT_M_START=BT_C_START");
    t.close(";ENDFOLD");
    t.open(";FOLD RESET: edge clears the warning, held 500 ms clears the error");
    t.open("IF BT_C_RESET THEN");
    t.open("IF NOT BT_M_RESET THEN");
    t.line("BT_WCODE=0");
    t.line(format!("$TIMER[{timer}]=0"));
    t.line(format!("$TIMER_STOP[{timer}]=FALSE"));
    t.close("ENDIF");
    t.open(format!("IF BT_ERR AND ($TIMER[{timer}]>=500) THEN"));
    t.line("BT_ERR=FALSE");
    t.line("BT_ECODE=0");
    t.line("BT_WCODE=0");
    t.close("ENDIF");
    t.dedent();
    t.open("ELSE");
    t.line(format!("$TIMER_STOP[{timer}]=TRUE"));
    t.close("ENDIF");
    t.line("BT_M_RESET=BT_C_RESET");
    t.close(";ENDFOLD");
    t.open(";FOLD NO FOLGE ACTIVE: STEP := 0, REQUEST := 0 (outputs persist after a cancel)");
    t.open("IF NOT BT_RUN OR BT_ABRT THEN");
    t.line("BT_STEP=0");
    for g in req_groups() {
        t.line(format!("{g}=0"));
    }
    t.close("ENDIF");
    t.close(";ENDFOLD");
    t.open(";FOLD STATUS");
    // The Folge (robot interpreter) sets BT_FIN before it clears BT_RUN, but this submit pass
    // can be interrupted between any two statements, and the bus takes $OUT at any moment. So:
    // read BT_RUN first (once it reads FALSE, BT_FIN already reads TRUE), publish ProgFinished
    // before ProgRunning. No bus frame then shows ProgRunning low with a stale ProgFinished low.
    t.comment(
        "ProgRunning low only after ProgFinished is out: read BT_RUN first, write BT_O_FIN first",
    );
    t.line("BT_PRUN=BT_RUN AND NOT BT_ABRT");
    t.line("BT_O_FIN=BT_FIN");
    t.line("BT_O_RUN=BT_PRUN");
    t.line("BT_O_DRIVES=$PERI_RDY");
    let home: Vec<String> = (1..=6)
        .map(|a| format!("(ABS($AXIS_ACT.A{a}-BT_HOME.A{a})<={tol})"))
        .collect();
    t.line(format!("BT_O_HOME={}", home.join(" AND ")));
    t.line("BT_O_INPOS=NOT BT_RUN");
    t.line("BT_O_EXT=($MODE_OP==#EX)");
    t.line("BT_O_READY=BT_READY");
    t.line("BT_O_ERROR=BT_ERR");
    t.line("BT_O_WARN=(BT_WCODE<>0)");
    t.line("BT_O_GATES=$USER_SAF");
    t.line("BT_O_ESTOP=$ALARM_STOP");
    t.line("BT_O_JOBACK=BT_ACK");
    t.line("BT_O_PERIPH=TRUE");
    t.line("BT_ECHO=BT_JOBNR");
    t.line("BT_ERRCODE=BT_ECODE");
    t.line("BT_WARNCODE=BT_WCODE");
    t.close(";ENDFOLD");
    if ctx.cfg.sim.joint_encoder {
        t.open(";FOLD JOINT ENCODER: A1..A6 as INT16 big-endian, 0.02 deg/count, bytes 16-27");
        for a in 1..=6u16 {
            t.line(format!("BT_Q=$AXIS_ACT.A{a}*50"));
            t.open("IF BT_Q<0 THEN");
            t.line("BT_Q=BT_Q+65536");
            t.close("ENDIF");
            let (h, l) = (2 * (a - 1), 2 * (a - 1) + 1);
            t.line(format!("BT_JNT{h}=(BT_Q-(BT_Q B_AND 255))/256"));
            t.line(format!("BT_JNT{l}=BT_Q B_AND 255"));
        }
        t.close(";ENDFOLD");
    }
    t.dedent();
    t.raw("END");
    t.finish(ctx.cfg.output.line_ending)
}
