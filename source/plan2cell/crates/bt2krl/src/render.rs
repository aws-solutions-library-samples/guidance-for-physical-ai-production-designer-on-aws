//! IR -> KRL text (TASK section 7). The Folge layout is shared; the profile decides how the
//! request, grant and release instructions are written. [`crate::parse`] reads exactly this
//! subset back.

use crate::config::{Config, NameStyle, Profile};
use crate::io::{self, SimIo};
use crate::ir::{Folge, FolgeKind, Instr, Point};
use crate::krl::{Text, ascii, num, secs};
use crate::lower::RobotSetup;
use crate::program::Program;

pub const GENERATOR: &str = concat!("bt2krl ", env!("CARGO_PKG_VERSION"));

/// Everything the renderers need besides the IR.
pub struct Ctx<'a> {
    pub p: &'a Program,
    pub s: &'a RobotSetup,
    pub cfg: &'a Config,
    pub profile: Profile,
    pub io: SimIo,
    /// Zone -> VW interlock index (profile `vw-ks24` only).
    pub il: Option<crate::vw::Interlocks>,
}

impl Ctx<'_> {
    pub fn file_stem(&self, folge: u16) -> String {
        match self.cfg.output.program_name_style {
            NameStyle::Lower => format!("folge{folge}"),
            NameStyle::Upper => format!("FOLGE{folge}"),
        }
    }

    pub fn plan_hex(&self) -> String {
        format!("16#{:04X}", self.p.plan_id())
    }

    fn zone_name(&self, bit: u32) -> String {
        if bit == 31 {
            return "PERMIT".into();
        }
        self.p
            .zones
            .iter()
            .find(|z| u32::from(z.bit) == bit)
            .map(|z| ascii(&z.name))
            .unwrap_or_else(|| format!("bit{bit}"))
    }

    fn header(&self, t: &mut Text, comment: &str) {
        t.raw("&ACCESS RVP");
        t.raw("&REL 1");
        t.raw(format!("&COMMENT {}", ascii(comment)));
    }

    /// Comment block describing the origin (inside DEF/DEFDAT).
    fn banner(&self, t: &mut Text) {
        let p = self.p;
        t.comment(format!(
            "Generated by {GENERATOR} from bt2plc plan {} (cell {}), PLAN_ID {}",
            p.plan.tree_id,
            p.plan.cell_id,
            self.plan_hex()
        ));
        t.comment(format!(
            "Robot {} ({}), controller {}, model {}, joint mapping {}",
            p.robot.ns,
            p.robot.tag,
            self.s.controller,
            self.s.model.name,
            p.joint_mapping.describe()
        ));
        match self.profile {
            Profile::Sim => {
                t.comment(
                    "Profile sim (bt2plc simulator telegram). NEVER install on a VW KS24 robot:",
                );
                t.comment(
                    "its signals collide with the VW standard (Fertigmeldung, interlocks, PRG_NR).",
                );
            }
            Profile::VwKs24 => t.comment("Profile vw-ks24 (VW KS24 / TPVW 8.1.8)."),
        }
        t.comment("Do not edit: regenerate with bt2krl (plain KRL, no inline forms).");
    }
}

fn axis_lit(pt: &Point) -> String {
    let mut s = String::from("{");
    for i in 0..6 {
        if i > 0 {
            s.push(',');
        }
        s.push_str(&format!("A{} {}", i + 1, num(pt.q[i])));
    }
    if let Some(e) = pt.e {
        for (i, v) in e.iter().enumerate() {
            s.push_str(&format!(",E{} {}", i + 1, num(*v)));
        }
    }
    s.push('}');
    s
}

pub fn point_decl(pt: &Point) -> String {
    let ty = if pt.e.is_some() { "E6AXIS" } else { "AXIS" };
    format!("DECL {ty} {}={}", pt.name, axis_lit(pt))
}

/// `$OUT[n]=TRUE ; REQ IL01` lines of a mask.
fn request_lines(ctx: &Ctx, t: &mut Text, mask: u32, on: bool) {
    for b in io::bits(mask) {
        let (v, what) = if on {
            ("TRUE", "REQ")
        } else {
            ("FALSE", "RELEASE")
        };
        t.line(format!(
            "$OUT[{}]={v} ; {what} {}",
            ctx.io.req_bit(b),
            ctx.zone_name(b)
        ));
    }
}

fn grant_cond(ctx: &Ctx, mask: u32, set: bool) -> String {
    io::bits(mask)
        .iter()
        .map(|&b| {
            let n = ctx.io.grant_bit(b);
            if set {
                format!("$IN[{n}]")
            } else {
                format!("NOT $IN[{n}]")
            }
        })
        .collect::<Vec<_>>()
        .join(" AND ")
}

pub fn home_move_lines(ctx: &Ctx, t: &mut Text, pt: &Point, time_ms: u64) {
    let vmax = ctx.s.model.vmax;
    let m = &ctx.cfg.motion;
    t.open(format!(";FOLD HOME MOVE {} {} S", pt.name, secs(time_ms)));
    t.comment("Velocity from the current pose so that the PTP takes about the home time");
    for (i, v) in vmax.iter().enumerate() {
        let var = if i == 0 { "BT_V" } else { "BT_T" };
        t.line(format!(
            "{var}=ABS({}.A{a}-$AXIS_ACT.A{a})/{}",
            pt.name,
            num(*v),
            a = i + 1
        ));
        if i > 0 {
            t.open("IF BT_T>BT_V THEN");
            t.line("BT_V=BT_T");
            t.close("ENDIF");
        }
    }
    let t_s = time_ms as f64 / 1000.0 * m.time_margin;
    t.line(format!("BT_V=100.0*BT_V/{}", num(t_s.max(0.001))));
    t.open(format!("IF BT_V<{} THEN", num(f64::from(m.min_vel_pct))));
    t.line(format!("BT_V={}", num(f64::from(m.min_vel_pct))));
    t.close("ENDIF");
    t.open(format!("IF BT_V>{} THEN", num(f64::from(m.max_vel_pct))));
    t.line(format!("BT_V={}", num(f64::from(m.max_vel_pct))));
    t.close("ENDIF");
    t.line("BAS(#VEL_PTP,BT_V)");
    t.line(format!("PTP {}", pt.name));
    t.close(";ENDFOLD");
}

pub fn check_start_line(pt: &Point, tol_mdeg: u32) -> String {
    let tol = num(f64::from(tol_mdeg) / 1000.0);
    let cond: Vec<String> = (1..=6)
        .map(|a| format!("(ABS($AXIS_ACT.A{a}-{}.A{a})>{tol})", pt.name))
        .collect();
    format!("IF {} THEN", cond.join(" OR "))
}

/// Render one instruction. `vel` tracks the last `BAS(#VEL_PTP)` value.
pub fn instr(ctx: &Ctx, f: &Folge, t: &mut Text, ins: &Instr, vel: &mut Option<u8>) {
    let codes = &ctx.p.protocol.error_codes;
    match ins {
        Instr::Init {
            approx_pct,
            tool,
            base,
        } => {
            t.open(";FOLD INI");
            t.line("BAS(#INITMOV,0)");
            t.line("$ADVANCE=3");
            t.line(format!("$APO.CPTP={approx_pct}"));
            if *tool > 0 {
                t.line(format!("BAS(#TOOL,{tool})"));
            }
            if *base > 0 {
                t.line(format!("BAS(#BASE,{base})"));
            }
            t.close(";ENDFOLD");
            *vel = None;
        }
        Instr::CheckPlan(id) if ctx.profile == Profile::VwKs24 => {
            crate::render_vw::plan_check(ctx, t, *id);
        }
        Instr::CheckPlan(id) => {
            t.open(format!(";FOLD PLAN ID 16#{id:04X}"));
            t.open("IF BT_PLANL<>PLAN_ID THEN");
            t.line(format!("BT_ECODE={}", codes.plan_mismatch));
            t.line("BT_ERR=TRUE");
            t.line("RETURN");
            t.close("ENDIF");
            t.close(";ENDFOLD");
        }
        Instr::Running => t.line("BT_RUN=TRUE"),
        Instr::CheckStart { point, tol_mdeg } => {
            let pt = &f.points[*point];
            t.open(format!(
                ";FOLD START DEVIATION {} {}",
                pt.name,
                num(f64::from(*tol_mdeg) / 1000.0)
            ));
            t.open(check_start_line(pt, *tol_mdeg));
            t.line(format!("BT_WCODE={}", codes.start_deviation));
            t.close("ENDIF");
            t.close(";ENDFOLD");
        }
        Instr::AbortGuard => {
            t.open("IF BT_ABRT THEN");
            t.line("RETURN");
            t.close("ENDIF");
        }
        Instr::SetStep(k) => {
            if ctx.profile == Profile::VwKs24 {
                t.line(crate::render_vw::step_line(ctx, *k));
            } else {
                t.line(format!("BT_STEP={k}"));
            }
        }
        Instr::Request(m) => request_lines(ctx, t, *m, true),
        Instr::WaitGrant(m) => t.line(format!("WAIT FOR {} ; GRANT", grant_cond(ctx, *m, true))),
        Instr::Delay(d) => t.line(format!("WAIT SEC {} ; start delay", secs(*d))),
        Instr::Move {
            point,
            vel_pct,
            approx,
        } => {
            if *vel != Some(*vel_pct) {
                t.line(format!("BAS(#VEL_PTP,{vel_pct})"));
                *vel = Some(*vel_pct);
            }
            let name = &f.points[*point].name;
            if *approx {
                t.line(format!("PTP {name} C_PTP"));
            } else {
                t.line(format!("PTP {name}"));
            }
        }
        Instr::HomeMove { point, time_ms } => {
            home_move_lines(ctx, t, &f.points[*point], *time_ms);
            *vel = None;
        }
        Instr::Hold(h) => t.line(format!("WAIT SEC {} ; hold", secs(*h))),
        Instr::Dwell(d) => t.line(format!("WAIT SEC {} ; step dwell", secs(*d))),
        Instr::Release(m) => request_lines(ctx, t, *m, false),
        Instr::WaitReleased(m) => t.line(format!(
            "WAIT FOR {} ; GRANT released",
            grant_cond(ctx, *m, false)
        )),
        Instr::Finish => {
            // Advance-run stop first: with $ADVANCE=3 the assignments would otherwise run
            // while the last exact-stop motion still moves (ProgFinished on a moving robot).
            t.open(";FOLD FINISH");
            t.line("WAIT SEC 0 ; advance-run stop");
            t.line("BT_STEP=0");
            t.line("BT_FIN=TRUE");
            t.line("BT_RUN=FALSE");
            t.close(";ENDFOLD");
        }
        Instr::Done => {
            t.open(";FOLD DONE");
            t.line("WAIT SEC 0 ; advance-run stop");
            t.line("BT_FIN=TRUE");
            t.line("BT_RUN=FALSE");
            t.close(";ENDFOLD");
        }
        vw => crate::render_vw::instr(ctx, &f.points, t, vw, vel),
    }
}

fn uses_home_move(f: &Folge) -> bool {
    f.instrs().any(|i| matches!(i, Instr::HomeMove { .. }))
}

pub fn op_fold_title(o: &crate::ir::OpBlock) -> String {
    format!(
        ";FOLD OP {} {} MASK 16#{:08X}",
        o.index, o.operation_id, o.mask
    )
}

pub fn folge_src(ctx: &Ctx, f: &Folge) -> String {
    let mut t = Text::default();
    let what = match f.kind {
        FolgeKind::Production => "production",
        FolgeKind::Home => "home",
    };
    ctx.header(
        &mut t,
        &format!(
            "bt2krl {} {} Folge {} plan {}",
            ctx.profile.name(),
            what,
            f.number,
            ctx.plan_hex()
        ),
    );
    t.raw(format!("DEF {}()", f.name()));
    t.indent();
    if uses_home_move(f) {
        t.line("DECL REAL BT_V,BT_T");
    }
    ctx.banner(&mut t);
    match (f.kind, ctx.profile) {
        (FolgeKind::Production, Profile::VwKs24) => {
            t.comment(format!(
                "Production Folge: {} ops; per op: op index BT_PKTNR, interlock request + MAKRO20 \
                 handshake, motion (exact stop at the end), hold, interlock release",
                f.ops.len()
            ));
            t.comment(
                "The VW tech package does the Folge handshake (cell.src, AUE_INIT/WAIT/END).",
            );
        }
        (FolgeKind::Production, _) => {
            t.comment(format!(
                "Production Folge: {} ops; per op: STEP, REQUEST, wait GRANT, delay, motion \
                 (exact stop at the end), hold, REQUEST := 0, wait GRANT released",
                f.ops.len()
            ));
        }
        (FolgeKind::Home, _) => {
            t.comment("HOME Folge: blind joint PTP to home_pose_deg; no step, no zones");
        }
    }
    let mut vel = None;
    for i in &f.prologue {
        instr(ctx, f, &mut t, i, &mut vel);
    }
    for o in &f.ops {
        let zones: Vec<String> = io::bits(o.mask).iter().map(|&b| ctx.zone_name(b)).collect();
        t.open(op_fold_title(o));
        if !zones.is_empty() {
            t.comment(format!("zones {}", zones.join(" ")));
        }
        for i in &o.instrs {
            instr(ctx, f, &mut t, i, &mut vel);
        }
        t.close(";ENDFOLD");
    }
    for i in &f.epilogue {
        instr(ctx, f, &mut t, i, &mut vel);
    }
    t.dedent();
    t.raw("END");
    t.finish(ctx.cfg.output.line_ending)
}

pub fn folge_dat(ctx: &Ctx, f: &Folge) -> String {
    let mut t = Text::default();
    ctx.header(
        &mut t,
        &format!(
            "bt2krl {} data Folge {} plan {}",
            ctx.profile.name(),
            f.number,
            ctx.plan_hex()
        ),
    );
    t.raw(format!("DEFDAT {}", f.name()));
    t.indent();
    ctx.banner(&mut t);
    t.line("EXT BAS (BAS_COMMAND :IN,REAL :IN )");
    if ctx.profile == Profile::VwKs24 {
        t.comment("interface to the VW standard routines (as every VW Folge .dat declares them)");
        t.line("EXT VW (VW_COMMAND :IN,BOOL :IN,REAL :IN,REAL :IN,REAL :IN,REAL :IN,BOOL :IN,E6POS :IN )");
        t.line("EXT VW_USR_R (VW_USER_CMD :IN,INT :IN,REAL :IN,REAL :IN,REAL :IN,REAL :IN,REAL :IN,REAL :IN,BOOL :IN )");
        t.line("EXTFCT INT SELECT (SUBTYPE :IN,INT :IN,BOOL :IN,ARI_TYP :IN,INT :IN,BOOL_TYP :IN,INT :IN,BOOL :IN)");
    }
    if let Some(id) = f.instrs().find_map(|i| match i {
        Instr::CheckPlan(id) => Some(*id),
        _ => None,
    }) && ctx.profile != Profile::VwKs24
    {
        t.line(format!("DECL INT PLAN_ID={id}"));
    }
    for pt in &f.points {
        t.line(point_decl(pt));
    }
    t.dedent();
    t.raw("ENDDAT");
    t.finish(ctx.cfg.output.line_ending)
}

