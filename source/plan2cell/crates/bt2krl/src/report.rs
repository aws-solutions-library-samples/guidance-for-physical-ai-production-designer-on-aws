//! `bt2krl-manifest.json` and `INSTALL.md` per robot.

use serde::{Deserialize, Serialize};

use crate::config::{EAxes, Profile};
use crate::krl::fnv1a64;
use crate::lower::{Lowered, OpEstimate};
use crate::render::{Ctx, GENERATOR};
use crate::validate::CheckCtx;
use crate::vw;

pub const MANIFEST_SCHEMA: &str = "bt2krl/manifest@1";
pub const MANIFEST_FILE: &str = "bt2krl-manifest.json";
pub const INSTALL_FILE: &str = "INSTALL.md";

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct FileHash {
    pub path: String,
    pub fnv1a64: String,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct ManifestRobot {
    pub ns: String,
    pub tag: String,
    pub controller: String,
    pub model: String,
    pub e_axes: String,
    pub joint_mapping: String,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct Manifest {
    pub schema: String,
    pub generator: String,
    pub tree_id: String,
    pub cell_id: String,
    pub plan_id: String,
    pub profile: String,
    pub motion: String,
    pub robot: ManifestRobot,
    pub folgen: Vec<u16>,
    /// Hashes of every other file of this robot (FNV-1a 64, hex).
    pub files: Vec<FileHash>,
    pub ops: Vec<OpEstimateOut>,
    pub warnings: Vec<String>,
    /// Validator context for `bt2krl check`.
    pub check: CheckCtx,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct OpEstimateOut {
    pub index: u16,
    pub operation_id: String,
    pub zone_mask: String,
    pub waypoints: usize,
    pub points: usize,
    pub est_s: f64,
    /// Motion only, against `planned_motion_s` (program.json `duration_s`).
    pub est_motion_s: f64,
    pub planned_motion_s: f64,
    pub expected_s: f64,
    pub limit_s: f64,
}

impl From<&OpEstimate> for OpEstimateOut {
    fn from(o: &OpEstimate) -> Self {
        OpEstimateOut {
            index: o.index,
            operation_id: o.operation_id.clone(),
            zone_mask: o.zone_mask.clone(),
            waypoints: o.waypoints,
            points: o.points,
            est_s: (o.est_s * 1000.0).round() / 1000.0,
            est_motion_s: o.est_motion_s,
            planned_motion_s: o.planned_motion_s,
            expected_s: o.expected_s,
            limit_s: o.limit_s,
        }
    }
}

pub fn e_axes_name(e: EAxes) -> &'static str {
    match e {
        EAxes::None => "none",
        EAxes::Fixed => "fixed",
        EAxes::Keep => "keep",
    }
}

pub fn manifest(ctx: &Ctx, l: &Lowered, files: &[(String, String)], check: CheckCtx) -> String {
    let p = ctx.p;
    let m = Manifest {
        schema: MANIFEST_SCHEMA.into(),
        generator: GENERATOR.into(),
        tree_id: p.plan.tree_id.clone(),
        cell_id: p.plan.cell_id.clone(),
        plan_id: ctx.plan_hex(),
        profile: ctx.profile.name().into(),
        motion: "ptp".into(),
        robot: ManifestRobot {
            ns: p.robot.ns.clone(),
            tag: p.robot.tag.clone(),
            controller: ctx.s.controller.clone(),
            model: ctx.s.model.name.into(),
            e_axes: e_axes_name(ctx.s.e_axes).into(),
            joint_mapping: p.joint_mapping.describe(),
        },
        folgen: std::iter::once(l.prod.number)
            .chain(l.home.as_ref().map(|h| h.number))
            .collect(),
        files: files
            .iter()
            .map(|(path, text)| FileHash {
                path: path.clone(),
                fnv1a64: format!("{:016x}", fnv1a64(text.as_bytes())),
            })
            .collect(),
        ops: l.estimates.iter().map(OpEstimateOut::from).collect(),
        warnings: l.warnings.clone(),
        check,
    };
    serde_json::to_string_pretty(&m).expect("manifest serialises") + "\n"
}

pub fn install_md(ctx: &Ctx, l: &Lowered, files: &[(String, String)]) -> String {
    let p = ctx.p;
    let s = ctx.s;
    let io = &ctx.io;
    let mut o = String::new();
    let w = |o: &mut String, line: &str| {
        o.push_str(line);
        o.push('\n');
    };
    w(
        &mut o,
        &format!(
            "# bt2krl: robot {} (controller {})",
            p.robot.ns, s.controller
        ),
    );
    w(&mut o, "");
    w(
        &mut o,
        &format!(
            "Generated by {GENERATOR} from bt2plc plan `{}` (cell `{}`), **PLAN_ID {}**, profile **{}**, motion `ptp`.",
            p.plan.tree_id,
            p.plan.cell_id,
            ctx.plan_hex(),
            ctx.profile.name()
        ),
    );
    w(
        &mut o,
        "The KRL and the head PLC must come from the same bt2plc run: any change of the plan, the",
    );
    w(
        &mut o,
        "blackboard, the bt2plc config or the bt2plc version changes PLAN_ID, and the production Folge then",
    );
    w(&mut o, "refuses to start (error 16#0103).");
    w(&mut o, "");
    if ctx.profile == Profile::Sim {
        w(&mut o, "## Never install this on a VW KS24 robot");
        w(&mut o, "");
        w(
            &mut o,
            "Profile `sim` uses the bt2plc simulator telegram. On the VW KS24 robots every one of its fields",
        );
        w(&mut o, "collides with signals the VW programs already use:");
        w(
            &mut o,
            "- step `$OUT[33..48]`: Fertigmeldung (A33-36), Typinfo (A37-39), `$COLL_ALARM` (A40), interlocks A41-48;",
        );
        w(
            &mut o,
            "- PLAN_ID `$IN[33..48]`: Fertigmeldung acknowledge, partner interlock releases E41-48;",
        );
        w(
            &mut o,
            "- REQUEST `$OUT[225..256]`: `VW_FEH_BIN_A` (A225-232), `Fzg_Typ_SPS` (A233-240);",
        );
        w(
            &mut o,
            "- GRANT bit 31 `$IN[128]`: used on all 8 exported robots;",
        );
        w(
            &mut o,
            "- bytes 0-3: `PRG_NR` E1-8, `SRB` E9, `$DRIVES_ON` E10, status A9-A24 and the PROFINET driver bits.",
        );
        w(&mut o, "");
        w(
            &mut o,
            "Use profile `vw-ks24` for those robots. Targets of `sim`: a plain KSS 8.x controller (OfficeLite, a",
        );
        w(
            &mut o,
            "test robot without the VW package) and the bt2plc co-simulation.",
        );
        w(&mut o, "");
    }
    w(&mut o, "## Files");
    w(&mut o, "");
    w(
        &mut o,
        "Copy onto the controller (paths below `C:\\KRC\\ROBOTER\\`, i.e. `KRC:\\R1\\...`):",
    );
    w(&mut o, "");
    w(&mut o, "| File | Content |");
    w(&mut o, "|---|---|");
    for (f, _) in files {
        let what = if f.contains(&format!("folge{}", l.prod.number))
            || f.contains(&format!("FOLGE{}", l.prod.number))
        {
            format!(
                "production Folge {} ({} ops)",
                l.prod.number,
                l.prod.ops.len()
            )
        } else if l.home.as_ref().is_some_and(|h| {
            f.contains(&format!("folge{}", h.number)) || f.contains(&format!("FOLGE{}", h.number))
        }) {
            format!(
                "HOME Folge {} (blind joint PTP to home)",
                l.home.as_ref().map(|h| h.number).unwrap_or(0)
            )
        } else if f.contains("bt_cell") {
            "job loop started in EXT mode, dispatches the Folgen".into()
        } else if f.ends_with("bt_sps.src") {
            "submit part: job handshake, status bits, abort latch, STEP/REQUEST clearing, joint encoder".into()
        } else if f.ends_with("bt_config.dat") {
            "declarations to merge into $config.dat (do not copy the file as a whole)".into()
        } else if f.ends_with("patches/KRC/R1/Folgen/cell.src") {
            "OPTIONAL: the CASE entry to add to the controller's cell.src".into()
        } else if f.ends_with("patches/KRC/R1/System/$config.dat") {
            "OPTIONAL: the same declarations with a patch header".into()
        } else if f == INSTALL_FILE || f == MANIFEST_FILE {
            "this file / the generation manifest (hashes, time estimates, warnings)".into()
        } else {
            String::new()
        };
        w(&mut o, &format!("| `{f}` | {what} |"));
    }
    w(&mut o, "");
    match ctx.profile {
        Profile::Sim => {
            w(&mut o, "Then edit two system files:");
            w(
                &mut o,
                "1. `KRC/R1/System/$config.dat`: paste the whole content of `bt_config.dat` into the fold",
            );
            w(
                &mut o,
                "   `USER GLOBALS` (it declares the `BT_*` signals and flags, and `BT_HOME`).",
            );
            w(
                &mut o,
                "2. `KRC/R1/System/sps.sub`: add the line `BT_SPS()` inside the `LOOP` (fold `USER PLC`).",
            );
            w(
                &mut o,
                "3. Select `KRC/R1/Program/bt_cell.src` as the program that Automatic External starts.",
            );
        }
        Profile::VwKs24 => {
            w(
                &mut o,
                "The VW tech package provides everything else. Two files that already exist must be edited:",
            );
            w(
                &mut o,
                &format!(
                    "1. `KRC/R1/Folgen/cell.src`: add `CASE {n}` with `FOLGE{n}()` to the `SWITCH PGNO` block \
                     (`CASE 0` of `SWITCH P_TYPE`), next to the cases that are already there.",
                    n = l.prod.number
                ),
            );
            w(
                &mut o,
                "2. `KRC/R1/System/$config.dat`: paste the fold from `bt_config.dat` into `USER GLOBALS`.",
            );
            if ctx.cfg.vw_ks24.emit_patches {
                w(
                    &mut o,
                    "   `patches/` holds both edits as ready-made fragments. They are fragments, not",
                );
                w(
                    &mut o,
                    "   replacements: the controller's own `cell.src` and `$config.dat` carry cell-specific",
                );
                w(
                    &mut o,
                    "   VW content that bt2krl does not know, so never copy them over the originals.",
                );
            }
            w(&mut o, "");
            w(
                &mut o,
                &format!(
                    "Nothing is added to `sps.sub`, and there is no home Folge: VW `cell.src` starts a Folge \
                     only once `$IN_HOME` is set, so recovery from \"not at home\" stays manual (the operator \
                     jogs the robot home, or runs the cell's own Folge {}).",
                    ctx.p.folgen.home
                ),
            );
        }
    }
    w(&mut o, "");
    if ctx.profile == Profile::VwKs24 {
        vw_sections(ctx, &mut o);
    }
    if ctx.profile == Profile::Sim {
        w(
            &mut o,
            "## Automatic External mapping (machine data; bt2krl does not write it)",
        );
        w(&mut o, "");
        w(
            &mut o,
            &format!(
                "The head PLC writes the commands into telegram bytes 0-1 (`$IN[{}..{}]`). Map in",
                io.input(0, 0),
                io.input(1, 7)
            ),
        );
        w(
            &mut o,
            "`KRC/STEU/Mada/$machine.dat` (or WorkVisual) so that the head can start `bt_cell` once:",
        );
        w(&mut o, "");
        w(&mut o, "| System signal | Suggested input | Why |");
        w(&mut o, "|---|---|---|");
        w(
            &mut o,
            &format!(
                "| `$EXT_START` | `$IN[{}]` (ProgStart pulse) | starts `bt_cell` the first time; later pulses are handled by `bt_sps` |",
                io.input(0, 1)
            ),
        );
        w(
            &mut o,
            &format!(
                "| `$DRIVES_ON` | `$IN[{}]` (DrivesOn) | drives on at the rising edge |",
                io.input(0, 0)
            ),
        );
        w(
            &mut o,
            &format!(
                "| `$DRIVES_OFF` | `$IN[{}]` (DrivesOn, low-active) | drives off when the head drops DrivesOn |",
                io.input(0, 0)
            ),
        );
        w(
            &mut o,
            "| `$MOVE_ENABLE` | the safety-rated motion enable of the cell | |",
        );
        w(
            &mut o,
            &format!(
                "| `$CONF_MESS` | `$IN[{}]` (Reset) | acknowledges messages with the head reset |",
                io.input(0, 5)
            ),
        );
        w(
            &mut o,
            "| `$PERI_RDY`, `$ALARM_STOP`, `$USER_SAF`, `$PRO_ACT` | (outputs, any free index) | read by `bt_sps` |",
        );
        w(&mut o, "");
        w(
            &mut o,
            "Keep the program override at 100 %: the head sends no override and its watchdogs assume the plan speed.",
        );
        w(
            &mut o,
            "The safe channel (PROFIsafe: head writes SafeOut0 = 16#01, SafeOut1 = 16#0F and needs SafeIn0.0 and",
        );
        w(
            &mut o,
            "SafeIn1.4) is the controller's SafeOperation configuration, not KRL.",
        );
        w(&mut o, "");
        w(&mut o, "## Telegram mapping");
        w(&mut o, "");
        w(
            &mut o,
            &format!(
                "Byte b, bit i of the DIO256 module is `$IN[{} + 8b + i + 1]` / `$OUT[{} + 8b + i + 1]` (`[sim] in_base`/`out_base`).",
                io.in_base, io.out_base
            ),
        );
        w(&mut o, "");
        w(&mut o, "| Field | Signals |");
        w(&mut o, "|---|---|");
        w(
            &mut o,
            &format!(
                "| STEP (op index, robot -> PLC) | `BT_STEP` = `$OUT[{}..{}]` |",
                io.step,
                io.step + 15
            ),
        );
        w(
            &mut o,
            &format!(
                "| REQUEST bit b (bit 31 = permit) | `$OUT[{}+b]` |",
                io.request
            ),
        );
        w(&mut o, &format!("| GRANT bit b | `$IN[{}+b]` |", io.grant));
        w(
            &mut o,
            &format!(
                "| PLAN_ID (PLC -> robot) | `BT_PLANID` = `$IN[{}..{}]` |",
                io.plan_id,
                io.plan_id + 15
            ),
        );
        w(
            &mut o,
            &format!(
                "| job number / echo | `BT_JOB` / `BT_ECHO` ({} bits) |",
                io.job_bits()
            ),
        );
        w(
            &mut o,
            "| error / warning code | `BT_ERRCODE` bytes 10-11, `BT_WARNCODE` bytes 12-13 |",
        );
        if ctx.cfg.sim.joint_encoder {
            w(
                &mut o,
                "| A1..A6 (monitoring) | `BT_JNT0..11` bytes 16-27, INT16 big-endian, 0.02 deg/count |",
            );
        }
        w(&mut o, "");
        w(
            &mut o,
            &format!(
                "`bt_cell` uses interrupt priority {} and `bt_sps` uses `$TIMER[{}]`; both must be free on the controller.",
                ctx.cfg.sim.interrupt_no, ctx.cfg.sim.reset_timer
            ),
        );
        w(&mut o, "");
    }
    w(&mut o, "## Robot data");
    w(&mut o, "");
    w(
        &mut o,
        &format!(
            "- Model `{}`{}.",
            s.model.name,
            if s.model.known() {
                ": every waypoint and the home pose are inside its software limits"
            } else {
                ": **unknown, software limits not checked**"
            }
        ),
    );
    w(
        &mut o,
        &format!(
            "- External axes: `e_axes = \"{}\"`{}.",
            e_axes_name(s.e_axes),
            match s.e_axes {
                EAxes::None =>
                    " (declared: the robot has no external axes; points are `AXIS`, A1-A6 only)",
                EAxes::Fixed =>
                    " (points are `E6AXIS` with the configured E1..E6 values: the external axes MOVE to them)",
                EAxes::Keep => "",
            }
        ),
    );
    w(
        &mut o,
        &format!(
            "- Home pose (program.json): {:?}; AtHome tolerance {} deg.",
            p.home_pose_deg, p.protocol.at_home_tol_deg
        ),
    );
    w(
        &mut o,
        &format!(
            "- Tool {} / base {} (0 = keep the current one).",
            s.tool_no, s.base_no
        ),
    );
    w(&mut o, "");
    w(&mut o, "## Joint mapping (unvalidated)");
    w(&mut o, "");
    w(
        &mut o,
        &format!(
            "The joint values are bt2plc's output after its URDF -> KUKA mapping `{}` (sign {:?}, offset {:?} deg).",
            p.joint_mapping.describe(),
            p.joint_mapping.sign,
            p.joint_mapping.offset_deg
        ),
    );
    w(
        &mut o,
        "bt2krl applies no further mapping. The URDF <-> KUKA mapping is **not validated** for these robots",
    );
    w(
        &mut o,
        "(`cell-data-replay/joint_map.yaml` suggests non-identity signs and offsets; its fit is unvalidated too).",
    );
    w(
        &mut o,
        "The limit check only catches gross mapping errors. Before the first automatic run, jog the robot",
    );
    w(
        &mut o,
        "to the first points of the production Folge in T1 and compare them with the planned poses.",
    );
    w(&mut o, "");
    w(&mut o, "## Motion and timing");
    w(&mut o, "");
    w(
        &mut o,
        &format!(
            "Approximated joint PTP (`C_PTP`, `$APO.CPTP = {}`), one `BAS(#VEL_PTP,v)` per segment from the planned",
            ctx.cfg.motion.approx_ptp_pct
        ),
    );
    w(
        &mut o,
        &format!(
            "segment time (decimation {} deg), exact stop at the end of every op. Estimated op times (start delay +",
            ctx.cfg.motion.decimate_tol_deg
        ),
    );
    w(
        &mut o,
        &format!(
            "motion + hold) against the plan. \"Motion s\" is the motion alone (segment times plus {} s for \
             one acceleration ramp) next to the planned `duration_s`; \"Estimated s\" adds the start delay \
             and the hold and is compared with the head's `expected_s` and watchdog `limit_s`:",
            ctx.cfg.motion.ramp_time_s
        ),
    );
    w(&mut o, "");
    w(
        &mut o,
        "| Op | Id | Mask | Waypoints -> points | Motion s | Planned s | Estimated s | Expected s | Limit s |",
    );
    w(&mut o, "|---|---|---|---|---|---|---|---|---|");
    for e in &l.estimates {
        w(
            &mut o,
            &format!(
                "| {} | {} | {} | {} -> {} | {:.3} | {:.3} | {:.3} | {} | {} |",
                e.index,
                e.operation_id,
                e.zone_mask,
                e.waypoints,
                e.points,
                e.est_motion_s,
                e.planned_motion_s,
                e.est_s,
                e.expected_s,
                e.limit_s
            ),
        );
    }
    w(&mut o, "");
    if !l.warnings.is_empty() {
        w(&mut o, "## Warnings");
        w(&mut o, "");
        for x in &l.warnings {
            w(&mut o, &format!("- {x}"));
        }
        w(&mut o, "");
    }
    w(&mut o, "## Not verified");
    w(&mut o, "");
    w(
        &mut o,
        "No local tool can compile KRL. bt2krl checks its own output with a strict validator, an IR round trip",
    );
    w(
        &mut o,
        "and (sim) a co-simulation of the same IR against the generated head PLC, but these points need a test",
    );
    w(
        &mut o,
        "on a real KSS 8.x controller before production use:",
    );
    w(
        &mut o,
        "- the generated files compile (syntax, `SIGNAL` declarations in `$config.dat`, calls without `EXT`);",
    );
    if ctx.profile == Profile::Sim {
        w(
            &mut o,
            "- abort: the interrupt `WHEN BT_ABRT` fires on Stop/Cancel while the Folge runs, brakes and RESUMEs into",
        );
        w(
            &mut o,
            "  `bt_cell`. If the robot interpreter itself was stopped (E-stop, drives off, stop key), check that the",
        );
        w(
            &mut o,
            "  interrupt fires when the program is restarted; otherwise the robot finishes the motion of the current",
        );
        w(
            &mut o,
            "  op before the abort guard returns. Until verified, recover from such a stop by resetting the program",
        );
        w(
            &mut o,
            "  (cancel) and re-selecting `bt_cell`, never by restarting it;",
        );
        w(
            &mut o,
            "- the job handshake timing of `bt_sps` against the head timeouts (5 s per step).",
        );
    }
    o
}

/// The `vw-ks24` sections of INSTALL.md: interlock table, signals, reserved signals.
fn vw_sections(ctx: &Ctx, o: &mut String) {
    let w = |o: &mut String, line: &str| {
        o.push_str(line);
        o.push('\n');
    };
    let v = &ctx.cfg.vw_ks24;
    w(o, "## Interlocks (VW standard A41-56 / A81-96)");
    w(o, "");
    w(
        o,
        "Each zone of the plan becomes one VW robot interlock. The partner robot must use the **same**",
    );
    w(
        o,
        "index, and the PLC must route `A(40+n)` of each robot to `E(40+n)` of the other and arbitrate",
    );
    w(o, "the requests `A(80+n)` into the grants `E(80+n)`.");
    w(o, "");
    w(
        o,
        "| Zone | Interlock | Release | Request | Grant | Partner release |",
    );
    w(o, "|---|---|---|---|---|---|");
    if let Some(il) = &ctx.il {
        for (z, n) in &il.map {
            w(
                o,
                &format!(
                    "| {z} | V{n} | `$OUT[{}]` | `$OUT[{}]` | `$IN[{}]` | `$IN[{}]` |",
                    vw::release_out(*n),
                    vw::request_out(*n),
                    vw::grant_in(*n),
                    vw::partner_in(*n)
                ),
            );
        }
    }
    w(o, "");
    w(
        o,
        "Entering runs the MAKRO20 semantics inline: request, wait for the PLC grant, wait for the",
    );
    w(
        o,
        "partner release, drop the own release (\"occupied\"), clear the request. Every wait carries the",
    );
    w(
        o,
        "VW operator escape `OR (NOT $LOOP_CONT AND ($MODE_OP<>#EX))`, which cannot trigger in EXT mode,",
    );
    w(
        o,
        "so automatic operation never leaves a wait without its grant. Leaving sets `A(40+n)` again;",
    );
    w(o, "the VW scheme has no 4-phase handshake.");
    w(o, "");
    if v.online_stop {
        w(
            o,
            &format!(
                "While an interlock is held, the partner release is part of the online driving condition \
                 `$CYCFLAG[{}]` that INTERRUPT {} watches (`VW(#FB_STOP)`), so the robot stops on the path \
                 if the partner withdraws its release.",
                vw::FB_CYCFLAG,
                vw::FB_INTERRUPT
            ),
        );
        w(o, "");
    }
    let (base, name) = vw::step_signal(v);
    w(o, "## Other signals");
    w(o, "");
    w(
        o,
        &format!(
            "- Op index: `{name}` = `$OUT[{base}..{}]`{}.",
            base + 15,
            if base == vw::STEP_OUT_VW {
                " (declared by bt_config.dat on the outputs of the VW `P_PktNr_SPS`, which is local \
                 to `vw_usr_r` and so cannot be written from a Folge)"
            } else {
                " (declared by bt_config.dat)"
            }
        ),
    );
    w(
        o,
        &format!(
            "- Home: `$OUT[{}]` (PF0) is set at P0 and cleared at the cycle start.",
            vw::PF0_OUT
        ),
    );
    w(
        o,
        "- Folge selection, start, echo and end stay with the VW package: `PRG_NR` `$IN[1..8]`,",
    );
    w(
        o,
        "  `SRB` `$IN[9]`, `PRG_NR_REFL` `$OUT[1..8]`, Folge end `$OUT[14]`.",
    );
    if v.makro0 {
        w(
            o,
            "- `SPSMAKRO0` at P0 resets A33-A96 (Fertigmeldung, Typinfo, interlocks **and the tool",
        );
        w(
            o,
            "  releases A57-A80**), as every VW sample Folge does. Set `makro0 = false` if your cell must",
        );
        w(o, "  not reset the tool releases at the home point.");
    }
    if v.makro50 {
        w(
            o,
            "- `SPSMAKRO50` at the cycle start builds the cyclic flags of the driving conditions.",
        );
    }
    if v.makro15 > 0 {
        w(
            o,
            &format!(
                "- `SPSMAKRO{}` (Gesamtfertigmeldung) at the last op, before the home point.",
                v.makro15
            ),
        );
    }
    if v.weld_call.is_empty() {
        w(
            o,
            &format!(
                "- No technology call is emitted: ops of type `{}` only wait their hold time. Set \
                 `vw_ks24.weld_call` to emit one (e.g. `SEL_RES=SELECT(#MAKRO,580,TRUE,,,,,FALSE)` or an \
                 EZSP `VW_USER` call).",
                v.weld_op_type
            ),
        );
    } else {
        w(
            o,
            &format!(
                "- Technology call for `{}` ops, during the hold: `{}`.",
                v.weld_op_type, v.weld_call
            ),
        );
    }
    w(o, "");
    if v.plan_id_byte == 0 {
        w(
            o,
            "**No PLAN_ID check.** The VW standard has no signal for it, so nothing stops a Folge",
        );
        w(
            o,
            "generated from one plan from running against a head PLC generated from another: the zone",
        );
        w(
            o,
            "numbering and the op order could then disagree silently. Set `vw_ks24.plan_id_byte` to a free",
        );
        w(
            o,
            "PLC -> robot byte to get the check, or re-deploy the KRL and the PLC strictly together.",
        );
    } else {
        w(
            o,
            &format!(
                "- PLAN_ID on the free PLC -> robot bytes {}-{} (`BT_PLANID`): a mismatch halts the Folge \
                 before any motion.",
                v.plan_id_byte,
                v.plan_id_byte + 1
            ),
        );
    }
    w(o, "");
    w(
        o,
        "Signals the generated code never writes: A33-A40 (Fertigmeldung, Typinfo, `$COLL_ALARM`),",
    );
    w(
        o,
        "A57-A80 (tool releases, apart from MAKRO0), A225-A240 (error code, vehicle type), and the",
    );
    w(
        o,
        "inputs E249/E250 (brake and mastering test). The validator enforces this.",
    );
    w(o, "");
}
